-- Настроение перестаёт быть эхом (Шаг 44).
--
-- До этой миграции `agent.mood` было одним словом без истории, и писатель у
-- него был один: `reflect_mood` после каждого обмена. Промпт спрашивал
-- буквально «каким стало настроение персонажа после этого обмена», ответ —
-- одно слово, и оно перезаписывало колонку целиком.
--
-- Отсюда три следствия, и все три ломают одно и то же.
--
-- **Настроение определялось последней репликой собеседника.** Написали резко —
-- расстроен; пошутили — повеселел. Это не характер, а зеркало с задержкой в
-- один ход: у персонажа не было НИЧЕГО, что сопротивлялось бы смене.
--
-- **Оно не имело причины.** Слово в базе есть, повода нет, и сказать «мне с
-- утра не по себе, с тех пор как ты рассказал про отца» персонаж не мог: он
-- не знал, отчего ему так. А человеческое настроение узнаётся именно тем, что
-- у него есть источник, переживший событие.
--
-- **Оно не имело возраста.** «Задумчивый» пять минут и «задумчивый» третий
-- день — разные состояния, и в промпте они выглядели одинаково.
--
-- Черты (Шаг 42) дают персонажу устойчивость на горизонте недель, канон — на
-- горизонте жизни. На горизонте часов у него не было ничего, и в разговоре
-- это заметнее всего остального: биография богатая, а в моменте — отражение
-- собеседника.

-- =============================================================================
-- Отчего и с каких пор
-- =============================================================================
-- Две колонки, а не одна, и вывести одну из другой нельзя: `mood_reason`
-- отвечает «почему», `mood_since` — «давно ли». Правило `0003_life.sql` про
-- флаг, дублирующий состояние, здесь не нарушается — это не флаг, а два
-- разных наблюдения об одном.
--
-- NULL у обеих — законное и притом начальное состояние: у новорождённого
-- настроение есть (колонка NOT NULL с умолчанием), а истории у него нет. Тот
-- же случай, что `traits_at IS NULL` после Шага 42 — «не считали ни разу», а
-- не «посчитали и вышло пусто». Читатель промпта на NULL рендерит строку так
-- же, как рендерил до этой миграции, и живая база переживает шаг без единой
-- правки.
ALTER TABLE agent ADD COLUMN mood_reason TEXT;
ALTER TABLE agent ADD COLUMN mood_since  TIMESTAMPTZ;

-- Ограничения «reason непуст ровно когда since не NULL» нет, и по той же
-- причине, по какой его нет у черт: законных состояний больше двух. Настроение
-- может смениться без внятного повода (и это честнее выдуманного), а
-- `mood_since` при этом обязано сдвинуться.

-- =============================================================================
-- Что меняется в поведении
-- =============================================================================
-- **`mood_since` двигается ТОЛЬКО при смене настроения.** Это и есть инерция:
-- пока слово то же, возраст растёт, и персонаж видит в промпте не «сейчас ты
-- задумчив», а «ты задумчив второй день». Двигай метку на каждом обмене — и
-- она стала бы копией `last_exchange_ts`, то есть вторым фактом об одном и
-- том же.
--
-- **Проход получает право ответить «прежнее», и это его обычный исход.**
-- Прежний промпт такого ответа не предусматривал: спрошенный «каким СТАЛО»,
-- он обязан был назвать слово, и называл — каждый раз новое. Отказ здесь той
-- же породы, что «нет» у любопытства и у обещаний: самый частый ответ, и он
-- не должен оставлять следа.
--
-- **Выцветание.** Настроение, не менявшееся дольше суток с лишним, перестаёт
-- ехать в промпт: блок выпадает целиком, как выпадают блоки черт, среды и
-- воспоминаний. Колонка при этом не трогается — забывать написанное незачем,
-- а описывать словом то, что уже не чувствуется, значит врать.
--
-- Возврата к «нейтральному» здесь НЕТ намеренно. Это был бы досев умолчания
-- поверх нажитого — ровно то, что Шаг 42 снял у черт: три правдоподобных
-- слова, поставленные автором вместо состояния, которого нет. Настроения
-- может не быть, и это законно: описывают то, что отличается от обычного.
