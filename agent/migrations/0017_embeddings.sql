-- До этой миграции в разговор всплывали три воспоминания, отобранные по весу
-- и давности (`recall_score`), — и ни одно не отбиралось по тому, О ЧЁМ
-- сейчас разговор. Спроси его про первый класс, и он вспомнит сон и отъезд,
-- потому что они свежее. Вектор смысла чинит именно это: к трём «тяжёлым»
-- добавляются те, что близки к реплике собеседника.

-- =============================================================================
-- Вектор у воспоминания
-- =============================================================================
-- **`REAL[]`, а не `vector` из pgvector, и это решение, а не экономия.**
-- pgvector требует пакета в системе и `CREATE EXTENSION`, который у роли без
-- прав суперпользователя падает, — и тогда падает миграция, а с ней демон.
-- Биография — это сотни, в пределе тысячи строк, и перебор 256-мерных
-- массивов в SQL на таком объёме укладывается в миллисекунды. Индекс
-- приближённого поиска здесь не нужен; понадобится — переезд на pgvector
-- будет одной миграцией, потому что формат числа тот же.
ALTER TABLE memories ADD COLUMN embedding REAL[];

-- Какой моделью посчитан вектор. Векторы разных моделей несравнимы, и
-- сравнение «вопрос одной моделью, воспоминание другой» даёт не ошибку, а
-- правдоподобный мусор. Поэтому сравнение идёт только внутри одной модели, а
-- смена модели в `.env` делает все прежние векторы «непосчитанными» — их
-- пересчитает фоновый проход.
ALTER TABLE memories ADD COLUMN embedding_model TEXT;

CREATE INDEX memories_embed_pending_idx ON memories (id)
    WHERE embedding IS NULL;

-- Скалярное произведение. Векторы кладутся нормированными (`embed.py`), и
-- тогда это и есть косинус. Считать норму здесь на каждом сравнении значило
-- бы платить за то, что уже сделано один раз при записи.
CREATE FUNCTION embed_dot(a REAL[], b REAL[])
RETURNS DOUBLE PRECISION LANGUAGE SQL IMMUTABLE STRICT PARALLEL SAFE AS $$
    SELECT sum(x::DOUBLE PRECISION * y::DOUBLE PRECISION)
      FROM unnest(a, b) AS t(x, y)
$$;
