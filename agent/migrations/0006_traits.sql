-- Метка, а не счётчик пересчётов и не копия числа воспоминаний. Вопрос, на
-- который она отвечает, ровно один: сколько нового накопилось с тех пор, —
-- и отвечается он соединением с `memories.created_at`, а не вторым числом,
-- обязанным не отставать.
--
-- NULL — не пересчитывали ни разу. Это же признак «пора считать всё, что
-- есть», и другого заводить не надо: правило `0003_life.sql` про флаг,
-- дублирующий состояние.
--
-- **Существующие черты эта миграция НЕ трогает, и это отличает её от 0004.**
-- Там 'Некто' сносился, потому что был неотличим от настоящего имени и врал
-- о состоянии. Здесь врать нечему: черты живого персонажа — не ложь, а
-- устаревшее приближение, и снести их значило бы оставить его без характера
-- до ближайшей ночи. Они заменятся первым же пересчётом.
--
-- Новорождённый при этом остаётся БЕЗ ЧЕРТ: досев `DEFAULT_TRAITS` снимается
-- в `engine._ensure_agent` этим же шагом. Пустой список — законное состояние,
-- и читатели промптов его пропускают, как пропускают пустой блок
-- воспоминаний. Персонаж без черт выглядит недоописанным ровно до третьего
-- разговора, и это честнее, чем выглядеть кем-то, кем он не становился.
ALTER TABLE agent ADD COLUMN traits_at TIMESTAMPTZ;

-- Ограничения «traits непусты ровно когда traits_at не NULL» здесь нет, в
-- отличие от `agent_born_ck`. Состояний законных три, а не два: пусто и не
-- считали (чистый старт), непусто и не считали (живая база до этой
-- миграции), непусто и посчитано. Четвёртое — пусто и посчитано — тоже
-- законно: пересчёт, вернувший меньше трёх черт, метку двигает, а список
-- не трогает, чтобы не тратить модель на ту же неудачу каждую ночь.
--
-- Иными словами, связи между колонками нет, и придумывать её ради симметрии
-- с рождением значило бы запретить состояние, в котором база находится
-- прямо сейчас.

