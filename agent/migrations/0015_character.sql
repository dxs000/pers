-- Характер: у черт появляется история, у персонажа — чего он хочет (Шаг 56).
--
-- До этой миграции характер держался на двух вещах: списке черт в
-- `agent.traits` и открытых нитях. Черты отвечают «какой он», нити — «чем
-- занят сегодня». Вопрос «чего он хочет, чего боится, во что верит» не
-- записывался нигде, и потому всё, что персонаж делал в фоне, решал код:
-- какую ленту открыть, что читать, о чём видеть сон. Эта миграция заводит
-- место под ответ. Выбор действий по нему — следующий шаг, а не этот.

-- =============================================================================
-- История черт
-- =============================================================================
-- Проход черт с Шага 42 просит модель на каждую черту показать, «из чего это
-- видно», — и выбрасывает ответ: `set_traits` кладёт в `agent.traits` одни
-- слова. Основание жило ровно до строки лога. Отсюда два провала:
--
--   нельзя ответить, почему он упрямый, — хотя ответ был получен;
--   нельзя увидеть, КАК он менялся. «Отстранённый» появился в марте и ушёл в
--   июне — это и есть формирование характера, и именно оно не записывалось.
--
-- `agent.traits` при этом НЕ снимается. Он остаётся тем, что читает промпт,
-- и тем, что правит `set_traits` одним `UPDATE` вместе с меткой. История —
-- второй писатель рядом с ним, в той же единице, а не его замена: переводить
-- все чтения черт на `JOIN` ради того, чтобы узнать пять слов, незачем.
CREATE TABLE trait_history (
    id         BIGSERIAL   PRIMARY KEY,
    name       TEXT        NOT NULL,
    -- Из чего видно, словами прохода черт. Пишется, когда черта ПОЯВИЛАСЬ,
    -- и дальше не переписывается: основание появления — свидетельство, и
    -- правило то же, что у протухших импульсов.
    reason     TEXT        NOT NULL,
    set_at     TIMESTAMPTZ NOT NULL,
    dropped_at TIMESTAMPTZ,
    CONSTRAINT trait_history_name_ck   CHECK (length(btrim(name)) > 0),
    CONSTRAINT trait_history_reason_ck CHECK (length(btrim(reason)) > 0)
);
-- Открытая черта с одним именем ровно одна: «упрямый», вернувшийся после
-- того, как уходил, — новая строка, а не воскрешение старой. Уход и
-- возвращение — два события, и оба остаются видны.
CREATE UNIQUE INDEX trait_history_open_uq
    ON trait_history (name) WHERE dropped_at IS NULL;

-- =============================================================================
-- Побуждения: чего хочет, чего боится, во что верит, что не даёт покоя
-- =============================================================================
-- **Одна таблица на четыре рода, а не четыре таблицы.** Механика у них одна:
-- появилось из чего-то, крепнет, когда жизнь подтверждает, гаснет, когда не
-- подтверждает, закрывается. Правило то же, что у `threads.side` (0010).
--
-- **Без основания записи нет.** Каждое побуждение ссылается на строки
-- биографии (`drive_sources`), и писатель отвергает кандидата без ссылок. Это
-- та же дисциплина, что у черт («черта, под которую нельзя показать строку, не
-- называется»), но здесь она держится схемой, а не просьбой в промпте.
CREATE TABLE drives (
    id          BIGSERIAL   PRIMARY KEY,
    kind        TEXT        NOT NULL,
    -- Его словами, одной фразой. Не категория («безопасность»), а то, что он
    -- сказал бы себе сам («не хочу снова начинать с нуля в чужом городе»).
    text        TEXT        NOT NULL,
    -- Почему, одной фразой. Дублирует ссылки? Нет: ссылки говорят «из каких
    -- событий», фраза — «как он это связал». Одно и то же событие рождает
    -- разное у разных людей, и именно связь и есть характер.
    basis       TEXT        NOT NULL,
    strength    REAL        NOT NULL DEFAULT 1.0,
    opened_at   TIMESTAMPTZ NOT NULL,
    -- Когда жизнь последний раз его подтвердила. От него считается затухание
    -- (`drive_score`), как `recall_score` считается от `last_recalled`.
    touched_at  TIMESTAMPTZ NOT NULL,
    closed_at   TIMESTAMPTZ,
    -- «сбылось», «прошло», «разуверился», «ответил себе» — словом, как
    -- `threads.closed_why`. Закрытое не удаляется: чего человек хотел раньше и
    -- перестал — часть того, кем он стал.
    closed_why  TEXT,
    CONSTRAINT drives_kind_ck     CHECK (kind IN ('want', 'fear', 'belief', 'question')),
    CONSTRAINT drives_text_ck     CHECK (length(btrim(text)) > 0),
    CONSTRAINT drives_basis_ck    CHECK (length(btrim(basis)) > 0),
    CONSTRAINT drives_strength_ck CHECK (strength >= 0),
    CONSTRAINT drives_closed_ck   CHECK ((closed_at IS NULL) = (closed_why IS NULL))
);
CREATE INDEX drives_open_idx ON drives (touched_at DESC) WHERE closed_at IS NULL;

-- Из каких воспоминаний выросло. Отдельной таблицей, а не массивом `BIGINT[]`:
-- у массива нет внешнего ключа, и ссылка на строку, которой не существует,
-- легла бы в базу молча. Здесь такая вставка падает в писателе.
--
-- ON DELETE CASCADE по воспоминанию — не потеря основания, а его честность:
-- `memories` не чистится никем, и если однажды Curator уберёт строку, ссылка
-- на неё значила бы ровно ничего.
CREATE TABLE drive_sources (
    drive_id  BIGINT NOT NULL REFERENCES drives(id)   ON DELETE CASCADE,
    memory_id BIGINT NOT NULL REFERENCES memories(id) ON DELETE CASCADE,
    PRIMARY KEY (drive_id, memory_id)
);
CREATE INDEX drive_sources_memory_idx ON drive_sources (memory_id);

-- Затухание побуждения: полураспад 45 суток от последнего подтверждения.
-- Дольше, чем у воспоминаний (30): вспоминается конкретное, а хочется
-- долго. Страх, который месяц ничем не подкреплялся, ослабевает, но не
-- исчезает за неделю.
CREATE FUNCTION drive_score(strength REAL, touched_at TIMESTAMPTZ, at TIMESTAMPTZ)
RETURNS DOUBLE PRECISION LANGUAGE SQL IMMUTABLE AS $$
    SELECT strength * pow(
        0.5,
        greatest(EXTRACT(EPOCH FROM (at - touched_at)) / 86400.0, 0.0) / 45.0
    )
$$;

-- Метка прохода побуждений. Пустой исход записи не оставляет, и без метки
-- проход звался бы каждую минуту — довод `agent.day_at` (0009).
ALTER TABLE agent ADD COLUMN drives_at TIMESTAMPTZ;
