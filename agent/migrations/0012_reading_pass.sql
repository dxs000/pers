-- Заход чтения (Шаг 49): метка под проход, который может ничего не написать.
--
-- `0011_reading.sql` завёл полку, позицию, порции и заметки — всё, из чего
-- состоит чтение, — и оставил невызванным ровно одно: сам проход. Эта
-- миграция добавляет единственное, чего проходу не хватает, чтобы его можно
-- было позвать из фона.
--
-- =============================================================================
-- Почему метка всё-таки понадобилась
-- =============================================================================
-- `0011` сказал прямо, что метки под чтение в `agent` НЕТ намеренно:
--
--     здесь запись остаётся всегда — заход либо сдвинул позицию и записал
--     `readings`, либо не состоялся.
--
-- Это верно — и верно ровно про ту половину дела, которую `0011` видел. У
-- чтения оказалось две половины, и вторая ведёт себя наоборот.
--
-- **Читающий заход и правда всегда оставляет след.** Позиция сдвинулась,
-- строка в `readings` есть, «давно ли он читал» выводится из `books.read_at`.
-- Метка тут была бы вторым фактом об одном и том же — то самое, что
-- запрещает `0003_life.sql`.
--
-- **Выбирающий заход следа не оставляет.** Персонаж смотрит на полку и имеет
-- право не взять ничего: «не сегодня» — законный ответ, и он обязан быть
-- законным, иначе выбор превращается в обязанность, а вся затея была про
-- желание. Но отказ не пишет ни строки, и заслонка «не чаще раза в N часов»
-- держаться ей не на чем: фоновый круг ходит раз в минуту, и персонаж, один
-- раз сказавший «не сегодня», говорил бы это тысячу четыреста раз в сутки —
-- каждый раз вызовом модели.
--
-- Это тот же провал, из-за которого завёлся `day_at` (`0009_lived.sql`), и
-- те же слова годятся дословно: пустой исход — состоявшаяся работа, и
-- заслонка обязана его учесть.
--
-- =============================================================================
-- Одна метка на обе половины, а не две
-- =============================================================================
-- Соблазн — завести метку только под выбор (`picked_at` отвечает «когда взял»,
-- `books.read_at` — «когда читал», не хватает лишь «когда смотрел на полку»).
-- Отвергнуто: тогда у прохода стало бы две заслонки с разными числами, и
-- ответ на вопрос «почему он сегодня не читал» зависел бы от того, была ли у
-- него в руках книга. Снаружи это одно дело — «сел за чтение», — и мерить его
-- надо одной величиной.
--
-- `books.read_at` при этом остаётся и второй фактом не становится: он отвечает
-- на другой вопрос — «когда эту книгу открывали в последний раз», — и живёт
-- столько же, сколько книга. Метка в `agent` отвечает на «когда он вообще
-- садился читать», в том числе в тот день, когда книги у него не было.
--
-- Двигается ВСЕГДА, в том числе после отказа модели и после сетевого промаха.
-- Прецедент `traits_at` (`0006_traits.sql`): неудача — не повод повторять ту
-- же неудачу через пять секунд на тех же входах.
--
-- NULL — не садился ни разу.
ALTER TABLE agent ADD COLUMN read_at TIMESTAMPTZ;
