-- Чтение: первое дело, у которого есть результат вне базы (Шаг 48).
--
-- До этой миграции всё, что происходило с персонажем между разговорами,
-- сочинял вечерний проход из его же канона. Источника вне модели у жизни не
-- было ни одного: `0009_lived.sql` завёл пятый источник воспоминаний, но на
-- входе у него стоят те же воспоминания. Отсюда два следствия, и второе
-- важнее первого.
--
-- **Биография съезжает к правдоподобному среднему.** У модели нет источника
-- разнообразия, кроме собственного распределения, и через два месяца вечеров
-- получается человек, который ходит по редакции, пьёт кофе и откладывает
-- письмо. Промпт дня это предвидит («Чего в сцене быть НЕ должно:
-- значительности») и лечит симптом, потому что лечить причину ему нечем.
--
-- **Ничего сделанного не оставляет следа.** Прожитое — текст о тексте, и
-- полезным такой персонаж быть не может по устройству: всё, что он «сделал»,
-- существует только внутри собственной базы.
--
-- Чтение — первое дело, где это не так. Файл прочитан или не прочитан,
-- позиция сдвинулась или нет, и спорить с этим модель не может.
--
-- =============================================================================
-- Чего эта миграция НЕ делает
-- =============================================================================
-- Не заводит общий каркас дел («намерение → действие → результат»). Соблазн
-- велик и был высказан вслух, но это схема под то, чего мы ещё не знаем:
-- какие у него окажутся занятия, выяснится за два-три шага жизни, а не за эту
-- миграцию. Правило `0003_life.sql` — «заведём вместе с читателем, увидев,
-- что отбирается» — и `0009_lived.sql`, отклонивший таблицу дней по тому же
-- доводу. Каркас извлекается из двух настоящих дел, а не угадывается до них.
--
-- Не хранит текст книг. База — память персонажа; гигабайт чужих текстов в ней
-- превращает `pg_dump` из сохранения жизни в сохранение библиотеки. В базе
-- путь, длина и позиция; текст лежит файлом.
--
-- Не ходит в сеть. Гутенберг, Викитека и всё, у чего есть режим отказа, — свой
-- шаг и свой край. Здесь книга появляется потому, что человек положил файл на
-- полку.

-- =============================================================================
-- Книги
-- =============================================================================
-- Строка заводится сканером на КАЖДУЮ конвертированную книгу, а не на
-- выбранную: проходу выбора нужен каталог, и «уже читал», «бросил» он обязан
-- видеть там же, иначе возьмётся за брошенное на второй день.
--
-- `picked_at IS NULL` — лежит и не взята. Это же и признак «не читал ни разу»,
-- и другого заводить не надо: правило `0003_life.sql` про флаг, дублирующий
-- состояние.
CREATE TABLE books (
    id          BIGSERIAL PRIMARY KEY,

    -- Путь к ЧИСТОМУ тексту, относительный от корня библиотеки. Относительный,
    -- а не абсолютный: абсолютный привязывает память персонажа к машине, на
    -- которой он в тот день жил, и переезд сервера стал бы амнезией.
    --
    -- Уникален, потому что файл — это и есть тождество книги. Два имени у
    -- одного файла означали бы две книги с общей позицией.
    text_path    TEXT NOT NULL UNIQUE,

    -- Откуда конвертировали. Не для работы — для ответа на «почему тут каша»:
    -- по нему видно, что книга приехала сканом, а не из fb2, и правится это
    -- заменой источника, а не правкой памяти.
    source_path  TEXT,
    source_kind  TEXT,

    title       TEXT NOT NULL,
    author      TEXT,

    -- Длина ЧИСТОГО текста в символах. Хранится, потому что по ней считается
    -- «сколько осталось», а нормализовать файл ради одного числа на каждом
    -- заходе значило бы читать всю книгу, чтобы узнать, докуда дочитал.
    --
    -- Она же — единица позиции. Позиция в символах, а не в главах: глав нет у
    -- половины текстов, а порция обязана нарезаться одинаково и
    -- воспроизводимо.
    length      INT NOT NULL,

    -- Отчёт ворот качества, как его посчитал конвертер. JSONB, потому что
    -- форма принадлежит конвертеру, а не хранилищу, — тот же довод, что у
    -- `agent.outside_latch`.
    --
    -- В базу попадает только прошедшее ворота. Отчёт хранится не ради отбора,
    -- а ради разбирательства: книга читается странно — видно, с какими
    -- числами её пропустили, без повторного прогона конвертации.
    quality     JSONB,

    -- Когда взял и почему, ЕГО словами. Не для целостности — для ответа на
    -- «с чего он вдруг». Тот же довод, что у `promises.message_id`: причина
    -- переживает момент, в который возникла.
    picked_at   TIMESTAMPTZ,
    picked_why  TEXT,

    position    INT NOT NULL DEFAULT 0,
    -- Когда читал последний раз. Метки в `agent` под это НЕТ намеренно, в
    -- отличие от `day_at` (0009) и `traits_at` (0006). Там метка понадобилась,
    -- потому что пустой исход не оставляет записи; здесь оставляет всегда —
    -- заход либо сдвинул позицию и записал `readings`, либо не состоялся.
    read_at     TIMESTAMPTZ,

    closed_at   TIMESTAMPTZ,
    -- 'дочитал' | 'бросил'. Разницу несёт слово, а не второй флаг — как
    -- `threads.closed_why` (0010). Брошенная книга говорит о характере больше,
    -- чем дочитанная, и стирать её нельзя по тому же правилу, по которому не
    -- стираются протухшие импульсы: свидетельство важнее чистоты таблицы.
    closed_why  TEXT,

    CONSTRAINT books_length_ck   CHECK (length > 0),
    CONSTRAINT books_position_ck CHECK (position >= 0 AND position <= length),
    CONSTRAINT books_closed_ck   CHECK ((closed_at IS NULL) = (closed_why IS NULL)),
    -- Закрытая книга обязана быть взятой. Обратное неверно: взятая и
    -- незакрытая — это ровно та, которую он читает сейчас.
    CONSTRAINT books_picked_ck   CHECK (closed_at IS NULL OR picked_at IS NOT NULL),
    -- Причина есть ровно тогда, когда есть выбор. Полувзятая книга (взята без
    -- причины или причина без взятия) читается как рабочее состояние и жила бы
    -- в базе месяцами — тот же довод, что у `agent_born_ck` (0004).
    CONSTRAINT books_why_ck      CHECK ((picked_at IS NULL) = (picked_why IS NULL))
);

-- Открытая книга ровно одна. Приём тот же, что у `sessions_one_open_uq`
-- (0001): выражение вместо константы, частичный предикат, потому что NULL-ы в
-- уникальном индексе друг с другом не конфликтуют.
--
-- Инвариант код будет предполагать в трёх местах (проход чтения, проход
-- выбора, сборка снимка) и нигде не проверять. Держаться ему лучше индексом,
-- чем уверенностью, что писатель один: писатель один ровно до того дня, когда
-- книгу отметят прочитанной руками.
--
-- Человек, читающий четыре книги параллельно, бывает. Персонаж, у которого в
-- промпте четыре книги, — это четыре строки, конкурирующие с воспоминаниями за
-- внимание модели.
CREATE UNIQUE INDEX books_one_open_uq
    ON books ((closed_at IS NULL))
    WHERE closed_at IS NULL AND picked_at IS NOT NULL;

-- Каталог спрашивают целиком и редко (проход выбора), а «что читаю сейчас» —
-- часто и по одной строке. Индекс под второе.
CREATE INDEX books_unread_idx ON books (id) WHERE picked_at IS NULL;

-- =============================================================================
-- Порции
-- =============================================================================
-- Одна строка — один заход: сколько прочитано и что из этого осталось словами.
--
-- Конспект нужен не для отчёта, а для СЛЕДУЮЩЕЙ порции. Без него каждый заход
-- читает середину книги, не помня начала, и через неделю персонаж
-- пересказывает роман как сборник несвязанных сцен. Та же работа, что
-- `episodes.summary` делает с разговорами, и по той же причине: в промпт не
-- влезает всё, а помнить надо.
--
-- NULL в `conspectus` — порция прочитана, слов не нашлось. Законный исход, как
-- пустой день: пометка «прочитано» важнее пересказа, потому что позиция уже
-- сдвинулась и переиграть её нельзя.
CREATE TABLE readings (
    id         BIGSERIAL   PRIMARY KEY,
    book_id    BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    at         TIMESTAMPTZ NOT NULL,
    from_pos   INT         NOT NULL,
    to_pos     INT         NOT NULL,
    conspectus TEXT,
    CONSTRAINT readings_span_ck CHECK (to_pos > from_pos AND from_pos >= 0)
);
CREATE INDEX readings_book_idx ON readings (book_id, at);

-- Свёртки конспектов здесь НЕТ, и это названный долг, а не недосмотр. Пока
-- книга измеряется десятком порций, в промпт едут все; на трёхсотстраничном
-- романе их станет тридцать, и понадобится ровно то, что `episodes.summary`
-- сделал с разговорами, — второй уровень сжатия. Заведётся вместе с
-- читателем, когда станет видно, что сворачивается: правило `0003_life.sql`.
--
-- Предел у долга общий с двумя другими (`recall_score` без индекса в 0005,
-- `all_memories` без LIMIT): всё это упирается в объём промпта и снимется
-- одним шагом — отбором релевантного, а не тремя частными приёмами.

-- =============================================================================
-- Заметки на полях
-- =============================================================================
-- Не воспоминание и не ассершен. Ассершен отвечает на «какой он»,
-- воспоминание — на «что с ним было», заметка — на «что он подумал об этом
-- месте». Разное поведение при записи: ассершен сливается по паре
-- (key, value), воспоминание не переписывается никогда, заметка живёт ровно
-- столько, сколько он её помнит, и может не пригодиться вовсе.
--
-- **Заметка НЕ попадает в канон сама, и это главное решение шага.**
--
-- Соблазн очевидный: прочитал — запиши «сегодня читал Х». Но тогда у
-- `memories.source = 'lived'` станет два писателя с разными правилами, а два
-- правила «что считать противоречием» разъезжаются молча — ровно то, чего
-- `0009_lived.sql` избегал, заводя одни ворота на трёх писателей.
--
-- Поэтому чтение оставляет заметку, а в жизнь её переводит вечерний проход, у
-- которого уже есть и ворота `check_memory`, и нити, и право ответить
-- «ничего». Писатель `lived` остаётся один.
CREATE TABLE notes (
    id         BIGSERIAL   PRIMARY KEY,
    book_id    BIGINT      NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    -- ON DELETE SET NULL, а не CASCADE: заметка переживает уборку порций, как
    -- обещание переживает сессию, в которой прозвучало (0007). Мысль осталась,
    -- даже если забылось, на каком заходе она пришла.
    reading_id BIGINT      REFERENCES readings(id) ON DELETE SET NULL,
    at         TIMESTAMPTZ NOT NULL,

    -- О каком месте книги. Смещение, а не цитата: цитата — это кусок чужого
    -- текста в базе памяти, и хранить его незачем, когда есть файл и позиция.
    -- Понадобится показать — прочитается по смещению.
    at_pos     INT,

    text       TEXT        NOT NULL,

    -- Рассказал ли. Пара к `impulses.spoken_at` и по той же причине: мысль, о
    -- которой уже говорили, не должна всплыть вторым заходом.
    told_at    TIMESTAMPTZ,

    CONSTRAINT notes_text_ck CHECK (length(btrim(text)) > 0)
);
-- Потребитель спрашивает только нерассказанное и берёт свежее.
CREATE INDEX notes_untold_idx ON notes (at DESC) WHERE told_at IS NULL;
CREATE INDEX notes_book_idx ON notes (book_id, at);

-- =============================================================================
-- Новый род повода
-- =============================================================================
-- Симметричен сну (0005): проход пишет свой след и заводит импульс, а
-- рассказывает его `background_tick` на своих заслонках — не потому, что это
-- случилось только что.
--
-- Срок годности короткий по той же причине, что у сна: прочитанное утром и
-- вспомненное к ночи — уже не мысль, а справка. Само число живёт в `cycle`,
-- как и прочие: база хранит повод, решает цикл.
ALTER TABLE impulses DROP CONSTRAINT impulses_kind_ck;
ALTER TABLE impulses ADD  CONSTRAINT impulses_kind_ck CHECK (kind IN (
    'silence',      -- давно не разговаривали
    'weather',      -- за окном сменилось семейство погоды
    'curiosity',    -- незакрытый вопрос из прошлого разговора
    'anniversary',  -- годовщина эпизода
    'dream',        -- приснилось, хочет рассказать
    'reading'       -- прочитал, хочет рассказать
));

-- =============================================================================
-- Чего здесь нет
-- =============================================================================
-- Нет оценки книги числом. «Понравилось на 7» — анкета; отношение к
-- прочитанному живёт в заметках и в `closed_why`, то есть словами.
--
-- Нет цитат. См. `notes.at_pos`.
--
-- Нет полки «хочу прочитать». Список намерений, который никто не сокращает,
-- через месяц перестаёт что-либо значить — ровно то, что `0010_threads.sql`
-- сказал про `opened`. Захочет — возьмёт; каталог никуда не денется.
--
-- Нет связи книги с нитью (`threads`). Она напрашивается («читаю, потому что
-- собрался написать»), но сегодня её нечем заполнить: нити открывает вечерний
-- проход, а книгу выбирает свой, и связывать их пришлось бы третьим
-- суждением. Заведётся, если окажется, что он и правда берёт книги под дела.
