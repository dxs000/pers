-- У персонажа появляется настоящее (Шаг 46).
--
-- `0003_life.sql` перечислил четыре источника воспоминаний, и все четыре
-- смотрят назад:
--
--     genesis  — то, что было до памяти;
--     told     — то, что всплыло в разговоре;
--     inferred — то, что персонаж вывел о себе сам;
--     dream    — то, что приснилось, и это единственный источник без
--                собеседника.
--
-- Биография от этого росла ТОЛЬКО ВГЛУБЬ. Сон пишет `recalled` возрастом от
-- нуля до `age_now`, и модель почти всегда тянет в детство — там пусто и там
-- ей удобно. Биограф пишет то, что всплыло в разговоре, то есть тоже прошлое.
--
-- В результате между вчера и сегодня с персонажем НЕ ПРОИСХОДИЛО НИЧЕГО. Он
-- нигде не был, ни с кем не говорил, ничего не делал. Заговорить сам он мог
-- только про погоду, тишину, сон, недоспрошенное и — с Шага 45 — про дату;
-- то есть про собеседника, про окно и про календарь. Человек с богатым
-- детством и пустой неделей читается как амнезия наоборот, и читается быстро.
--
-- =============================================================================
-- Пятый источник
-- =============================================================================
-- `lived` — то, что было с ним сегодня. Пишется вечером по его месту, без
-- собеседника, ровно одним проходом.
--
-- **Симметричен сну и противоположен ему по направлению.** Сон пишет назад,
-- день пишет вперёд. Отсюда и устройство прохода: те же три заслонки по
-- природе (время суток, тишина, не чаще раза в сутки), тот же отказ от
-- разговора как входа, те же ворота сверки на выходе.
--
-- **Ворота сверки здесь обязательны, и это отличает `lived` от `dream`.**
-- Приснившееся не может противоречить биографии — сон и есть место, где всё
-- противоречит всему, потому и помечается отдельно. Прожитое противоречить
-- может: канон говорит, что он редактор в Тбилиси, а сцена — что он весь день
-- принимал роды в Гори. Такая строка ложится навсегда и тянет за собой все
-- последующие, поэтому идёт через `mind.check_memory` — те же ворота, что у
-- биографа и у вспомненного во сне. Три писателя, одни ворота: два разных
-- правила «что считать противоречием» разъехались бы молча.
ALTER TABLE memories DROP CONSTRAINT memories_source_ck;
ALTER TABLE memories ADD  CONSTRAINT memories_source_ck
    CHECK (source IN ('genesis', 'told', 'dream', 'inferred', 'lived'));

-- =============================================================================
-- Чего здесь нет
-- =============================================================================
-- Нет отдельной таблицы «дней». Соблазн понятный — у дня есть дата, погода,
-- настроение, занятие, — но это была бы вторая ось жизни рядом с `memories`,
-- и всё, что уже написано (отбор по `recall_score`, сверка, вес, вспоминание,
-- рендер в промпт), пришлось бы писать для неё заново. День — это сцена, а
-- сцены живут здесь.
--
-- Нет колонки под погоду или занятие. Сцена — текст, и разбирать его на поля
-- значило бы заводить схему под то, чего мы ещё не знаем: какие занятия у
-- него окажутся, выяснится за месяц жизни, а не за эту миграцию.
--
-- Нет `weight` по умолчанию иного, чем у прочих. Прожитый день не весомее
-- детства и не легче его: вес — это то, к чему персонаж возвращается, и
-- решать это должно вспоминание, а не источник. Единственное исключение в
-- проекте — свежий сон (`DREAM_WEIGHT = 1.6`), и оно обосновано тем, что сон
-- обязан всплыть в то же утро, иначе не всплывёт никогда. У дня такого срока
-- нет.

-- =============================================================================
-- Когда день подводили в последний раз
-- =============================================================================
-- Метка нужна ровно потому, что пустой день — законный исход. У сна такой
-- колонки нет и не надо: сон всегда что-то пишет, и «давно ли он спал»
-- выводится из самой таблицы (`last_dream_at`). День может быть спрошен и
-- ответить «ничего» — и тогда в `memories` не появится ничего, из чего это
-- видно.
--
-- Без метки заслонка «раз в сутки» держалась бы на записи, которой нет, и
-- пустой вечер звал бы модель каждые несколько секунд до полуночи — тысячи
-- вызовов за вечер, и ровно в тот вечер, когда персонажу нечего сказать.
--
-- Это НЕ второй факт об одном и том же (правило `0003_life.sql`): здесь
-- нечего дублировать, потому что дублировать нечего по определению. Точный
-- прецедент — `traits_at` из `0006_traits.sql`: там метка двигается и при
-- неудачном пересчёте, чтобы не повторять ту же неудачу каждую ночь.
--
-- NULL — не подводили ни разу.
ALTER TABLE agent ADD COLUMN day_at TIMESTAMPTZ;
