-- Имя приходит с рождением (Шаг 36.3).
--
-- До этой миграции `agent.name` имел дефолт 'Некто', и на чистой базе
-- персонаж существовал безымянным, но выглядел как персонаж по имени Некто.
-- Разница была безобидной ровно до тех пор, пока имени неоткуда было
-- взяться. Теперь оно берётся — из генезиса, — и 'Некто' стало ложью,
-- которую невозможно отличить от правды: читатель не может сказать, это
-- ещё не родившийся персонаж или родившийся с таким именем.
--
-- NULL отличается тем, что он не выглядит именем.

ALTER TABLE agent ALTER COLUMN name DROP DEFAULT;
ALTER TABLE agent ALTER COLUMN name DROP NOT NULL;

-- Строка в `agent` заведена миграцией 0001 (`INSERT INTO agent (id)`), то
-- есть с дефолтом. Условие — по `born_at`, а не по значению 'Некто': оно
-- делает ограничение ниже выполнимым ПО ПОСТРОЕНИЮ, а не по совпадению.
-- Проверять на строку значило бы поверить, что никто не вписал в имя
-- что-нибудь руками, — а если вписал, то ограничение упало бы посреди
-- миграции, и разбираться пришлось бы уже с полуприменённой схемой.
UPDATE agent SET name = NULL WHERE born_at IS NULL;

-- =============================================================================
-- Имя и дата рождения — одно событие
-- =============================================================================
-- Ограничение несущее, а не гигиеническое. Генезис пишет обе колонки одной
-- транзакцией, и это сегодня верно; ограничение делает это верным ЗАВТРА,
-- когда писателей станет двое или когда кто-нибудь поправит имя руками.
--
-- Полурождённый персонаж — не абстракция. Имя без даты даёт человека без
-- возраста: блок биографии не рендерится (`_render_memories` требует
-- `born`), воспоминания не датируются, годовщины не считаются. Дата без
-- имени даёт возраст без человека. Оба состояния читаются как рабочие и не
-- падают нигде — то есть жили бы в базе месяцами.
--
-- Равенство, а не два NOT NULL: «ещё не родился» — законное состояние
-- чистого старта, и запрещать его нельзя. Запрещается только половина.
--
-- `birthplace` в ограничение НЕ входит: место рождения может не
-- подтвердиться (геокодер молчит, модель насочиняла), и тогда генезис
-- ставит место жизни. Это законный исход, а не незавершённое рождение.
ALTER TABLE agent ADD CONSTRAINT agent_born_ck
    CHECK ((born_at IS NULL) = (name IS NULL));