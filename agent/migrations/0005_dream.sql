--
-- До этой миграции `memories` пополнялись ровно двумя путями: генезисом
-- (один раз за жизнь) и биографом (Шаг 38), который висит на T2, то есть на
-- обмене. Из этого следовало то, чего проект как раз избегает: путь развития
-- задавал собеседник. Спросили про школу — появилась школа; не спросили —
-- школы нет и не будет. Персонаж, живущий в фоне, при этом в фоне НЕ ЖИВЁТ:
-- он молчит, ждёт вопроса и от него достраивается.
--
-- Сон — единственный писатель, которому собеседник не нужен. Схему под него
-- заводить почти не пришлось: `memories.source = 'dream'`, `impulses.kind =
-- 'dream'` и `assertions.source = 'dream'` были названы заранее, в 0001 и
-- 0002. Миграция закрывает то, что заранее названо не было.

-- =============================================================================
-- Правило отбора всплывающего. Долг 0003, и он становится несущим ИМЕННО
-- сейчас
-- =============================================================================
-- `0003_life.sql` сказал прямо: функции затухания у воспоминаний нет,
-- `effective_salience` не переиспользуется (72 часа верны для объекта и
-- абсурдны для воспоминания), а заведётся правило вместе с читателем, когда
-- станет видно, что отбирается. `store_pg.build_snapshot` повторил это своими
-- словами: `ORDER BY weight DESC` временный, все значения приходят из
-- фикстура, писателя `weight` не существует.
--
-- Второй писатель отменяет обе оговорки разом. Воспоминаний станет больше,
-- чем `MEMORIES_LIMIT`, значения перестанут приходить из фикстура, и правило
-- отбора начнёт решать не «что показать», а КТО ПЕРСОНАЖ: в промпт попадают
-- три строки, и из них он себя каждый раз собирает.
--
-- Формула та же по устройству, что `effective_salience`, и это не копирование
-- по инерции — это единственное, что в проекте уже проверено сбруей как
-- порядок. Отличий два, и оба несущие:
--
--   период в СУТКАХ, а не в часах, и он тридцатидневный. Воспоминание обязано
--     пережить неделю молчания: 72-часовой период похоронил бы детство за
--     выходные, и персонаж, с которым не разговаривали три дня, вернулся бы к
--     разговору без прошлого;
--
--   отсчёт от `coalesce(last_recalled, created_at)`, а не от одной метки.
--     Ни разу не вспомненное воспоминание отсчитывается от записи — иначе оно
--     родилось бы уже забытым и не всплыло никогда, то есть сон писал бы в
--     стол.
--
-- IMMUTABLE при параметре `at` — тот же приём, что у `effective_salience`:
-- функция чиста относительно СВОИХ аргументов, а «сейчас» ей передаёт
-- вызывающий. Без этого её нельзя было бы поставить в `ORDER BY`.
CREATE FUNCTION recall_score(weight REAL, last_recalled TIMESTAMPTZ,
                             created_at TIMESTAMPTZ, at TIMESTAMPTZ)
RETURNS DOUBLE PRECISION LANGUAGE SQL IMMUTABLE AS $$
    SELECT weight * pow(
        0.5,
        greatest(
            EXTRACT(EPOCH FROM (at - coalesce(last_recalled, created_at)))
            / 86400.0,
            0.0
        ) / 30.0
    )
$$;

-- Индекса под этот `ORDER BY` НЕТ, и это решение, а не забывчивость.
-- Выражение зависит от `at`, то есть от момента запроса, и индексом такое не
-- накрывается в принципе — пришлось бы городить материализованный столбец со
-- вторым писателем, обязанным не отставать. Ровно та болезнь, которую Шаг 37
-- лечил вычитанием фонового писателя.
--
-- Цена названа: отбор — сортировка всей таблицы. Терпимо, пока биография
-- измеряется сотнями строк, и перестанет быть терпимым тогда же, когда
-- перестанет влезать в промпт сверки (`all_memories` без LIMIT). Оба предела
-- упираются в одно и то же и будут сняты одним шагом — отбором релевантного,
-- а не индексом.

-- =============================================================================
-- Сколько снов за ночь
-- =============================================================================
-- Водяного знака «когда снилось в последний раз» здесь нет, и колонки под
-- него тоже. Ответ уже лежит в таблице: `max(created_at) WHERE source =
-- 'dream'`. Отдельная метка была бы вторым фактом об одном и том же — то,
-- что 0003 запретил про `born_at`, а 0004 повторил про имя.
--
-- Индекс частичный, под этот единственный запрос. Снов меньшинство, и полный
-- индекс по `created_at` платил бы за строки, которые никто по этой оси не
-- спрашивает.
CREATE INDEX memories_dream_idx ON memories (created_at DESC)
    WHERE source = 'dream';
