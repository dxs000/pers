-- Шаг 63: всплыть — не значит вспомнить. Лечение персеверации.
--
-- ## Болезнь
--
-- С Шага 40 всякое воспоминание, попавшее в промпт, отмечалось вспомненным:
-- `last_recalled = now`, вес +0.1. Отбор — top-3 по `recall_score`, а
-- `recall_score` считает затухание ОТ `last_recalled`. Значит, попавшее в
-- тройку в тот же миг получает затухание ноль и прибавку, то есть лучший счёт
-- из возможных, и занимает тройку на следующем ходу. Обратная связь
-- замкнута, и потолок `RECALL_CEILING` её не размыкает: он ограничивает вес,
-- а замок держится на обнулённой давности.
--
-- Симуляция (30 строк биографии, 14 дней по три разговора): в промпт попало
-- 3 разных воспоминания из 30, каждое — в 100% реплик. Одно из трёх — сон
-- (`DREAM_WEIGHT = 1.6` сажал его в тройку первым же утром, навсегда).
-- Персонаж, который две недели рассказывает одни и те же три истории, и
-- одна из них ему приснилась, читается ровно как старик с деменцией.
--
-- ## Лечение: две метки вместо одной
--
--   surfaced_at — когда строка последний раз ЕХАЛА В ПРОМПТ. Ставится на
--                 каждом показе. Веса не трогает и давность не обнуляет.
--   told_at     — когда персонаж её последний раз РАССКАЗАЛ: строка
--                 всплыла, и ответ её задел. Только это — вспоминание, и
--                 только оно двигает `last_recalled` и вес, как раньше.
--
-- Отбор умножает `recall_score` на привыкание по `surfaced_at`:
--
--   в пределах разговора (меньше SESSION_GAP_HOURS = 3 ч) — 1, всплывшее
--   держится: человек не теряет нить посреди рассказа;
--   после разрыва — провал и восстановление с полупериодом двое суток: на
--   следующий день то же самое на ум почти не идёт, через неделю — снова.
--
-- Это не забывание: вес и биография не тронуты. Это то, что у живого
-- человека называется «об этом я уже думал, сейчас о другом».
--
-- ## Сны гаснут быстрее
--
-- Сон помнится утром и почти не помнится через три дня. Полупериод у
-- `source = 'dream'` — 2 суток вместо 30. Сон НЕ удаляется и остаётся в
-- каноне (проход сна, сверка, поиск по смыслу его видят); он лишь перестаёт
-- сам лезть на язык неделю спустя.
ALTER TABLE memories ADD COLUMN surfaced_at TIMESTAMPTZ;
ALTER TABLE memories ADD COLUMN told_at     TIMESTAMPTZ;

CREATE FUNCTION surface_score(weight REAL, last_recalled TIMESTAMPTZ,
                              created_at TIMESTAMPTZ, surfaced_at TIMESTAMPTZ,
                              source TEXT, at TIMESTAMPTZ)
RETURNS DOUBLE PRECISION LANGUAGE SQL IMMUTABLE AS $$
    SELECT weight
         * pow(0.5,
               greatest(EXTRACT(EPOCH FROM (at - coalesce(last_recalled, created_at)))
                        / 86400.0, 0.0)
               / CASE WHEN source = 'dream' THEN 2.0 ELSE 30.0 END)
         * CASE
             WHEN surfaced_at IS NULL THEN 1.0
             WHEN at - surfaced_at < interval '3 hours' THEN 1.0
             ELSE 1.0 - pow(0.5,
                            greatest(EXTRACT(EPOCH FROM (at - surfaced_at)) / 3600.0 - 3.0, 0.0)
                            / 48.0)
           END
$$;
