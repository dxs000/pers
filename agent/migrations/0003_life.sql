-- Ось жизни: у персонажа появляется «когда» (Шаг 36).
--
-- До этой миграции у персонажа не было ни одной метки времени, отвечающей
-- на вопрос «когда это случилось С НИМ». `assertions.ts` отвечает на другой
-- вопрос — «когда мы это в последний раз подтвердили», — а `episodes`
-- датируют разговоры, а не жизнь. Биографию к этому прицепить некуда, и
-- миграция заводит вторую ось, а не расширяет первую.

-- =============================================================================
-- Точка отсчёта
-- =============================================================================
-- NULL — не родился. Это единственный признак «генезис не прошёл», и другого
-- заводить не надо: флаг, дублирующий состояние, расходится с ним ровно тогда,
-- когда на него смотрят.
--
-- Дата тянется машиной, место называет модель и проверяет геокодер, но
-- координаты места рождения здесь НЕ хранятся. Они нужны один раз — сверить
-- расстояние в момент генезиса — и после этого не нужны никому: погода
-- считается по месту, где он сейчас (`place_lat`/`place_lon`), а место
-- рождения живёт в промпте словом. Понадобятся — добавятся своей миграцией;
-- аргумент `0001` про «ALTER задним числом дороже пустой таблицы» перестал
-- действовать в тот день, когда появились миграции.
ALTER TABLE agent ADD COLUMN born_at    TIMESTAMPTZ;
ALTER TABLE agent ADD COLUMN birthplace TEXT;

-- Пола здесь нет намеренно. Он не тянется и не хранится: проект целиком на
-- русском, род течёт через каждую служебную формулировку (`_build_reflector_prompt`,
-- `_build_extractor_prompt`, суммаризатор), и все они сегодня в мужском.
-- Пол — рамка мира, как `APP_PLACE` и возрастная вилка, а не факт, который
-- персонаж о себе узнаёт. Колонка появится в тот день, когда служебные
-- промпты перестанут его предполагать, и не раньше.

-- `agent.name` эта миграция не трогает, хотя 'Некто' — ложь, и снять его
-- надо. Снятие дефолта роняет `golden._fresh_engine` (`SET name = DEFAULT`
-- даст NULL) и вместе с ним половину эталонов — то есть красит сбрую по
-- причине, к схеме не относящейся. Имя переезжает вместе со своими
-- читателями, следующим шагом.

-- =============================================================================
-- Воспоминания. НЕ ассершены, и это несущее решение
-- =============================================================================
-- Ассершен отвечает на «какой он», воспоминание — на «что с ним было».
-- Разное поведение при записи: ассершен сливается по паре (key, value) и
-- обновляется, воспоминание записывается ОДИН РАЗ и не переписывается
-- никогда. Неизменяемость тут — не осторожность, а единственное, что
-- отличает биографию от потока галлюцинаций: модель без состояния при каждом
-- вопросе «расскажи о детстве» сочиняет новое детство, и только уже
-- записанное не даёт ей это сделать дважды.
CREATE TABLE memories (
    id          BIGSERIAL   PRIMARY KEY,

    -- Когда это случилось В ЕГО ЖИЗНИ. Точка на оси есть ВСЕГДА, даже когда
    -- события толком не датировать: неточность несёт `precision`, а не NULL.
    -- NULL означал бы «неизвестно когда», и такое воспоминание выпало бы из
    -- порядка жизни — то есть перестало быть биографией.
    happened_at TIMESTAMPTZ NOT NULL,

    -- Насколько верить дате при рендере: 'era' → «в детстве», 'day' → число.
    -- Детство днём не датируется, и попытка выдать точную дату превращает
    -- биографию в анкету — ровно то, чего шаг избегает.
    precision   TEXT        NOT NULL,

    -- Когда ЗАПИСАЛОСЬ. Вторая ось, и она не декоративна: приснившееся
    -- вчера про семилетнего — свежая запись о давнем, и рассортировать это
    -- по одной метке нельзя.
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),

    -- От первого лица, одна сцена. Не сводка и не период.
    text        TEXT        NOT NULL,

    source      TEXT        NOT NULL,

    -- Насколько сильно помнится. Правится на живом, как `urge`.
    weight      REAL        NOT NULL DEFAULT 1.0,
    last_recalled TIMESTAMPTZ,

    CONSTRAINT memories_precision_ck CHECK (precision IN ('day','month','year','era')),
    CONSTRAINT memories_source_ck    CHECK (source IN (
        'genesis',   -- при рождении: имя и его причина
        'told',      -- сказал в разговоре
        'dream',     -- приснилось (Шаг 37)
        'inferred'   -- вывел сам, вспоминая
    )),
    CONSTRAINT memories_weight_ck    CHECK (weight >= 0)
);

-- Биография читается в порядке жизни, а не записи.
CREATE INDEX memories_happened_idx ON memories (happened_at);

-- Функции затухания здесь нет, и `effective_salience` НЕ переиспользуется.
-- Типы совпадают, соблазн велик, но период полураспада там 72 часа — верно
-- для всплывающего объекта и абсурдно для воспоминания, которое обязано
-- пережить неделю молчания. Правило отбора всплывающего — забота читателя,
-- а читателя пока нет; заведём вместе с ним, увидев, что отбирается.

-- Ограничения `happened_at >= agent.born_at` тоже нет: оно межтабличное, и
-- CHECK его не выражает. Держать это обязан тот, кто пишет, — там же, где
-- лежит правило «не противоречить уже записанному».