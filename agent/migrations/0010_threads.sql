-- Незакрытое (Шаг 47).
--
-- После Шага 46 у персонажа есть прошлое и есть сегодня. Чего нет — связи
-- между вечерами: каждый день пишется заново, вчерашняя сцена подаётся в
-- промпт одной строкой, и дальше неё память дня не простирается. Начатое в
-- понедельник не доживает до четверга, потому что доживать ему негде.
--
-- Отсюда биография остаётся РОССЫПЬЮ СЦЕН. В ней есть события и нет линий, а
-- значит нет и ответа на вопрос, ради которого всё затевалось: куда он идёт.
-- Характер (Шаг 42) отвечает, каким он стал; канон — что с ним было; но
-- «чем это кончится» не отвечает ничто.
--
-- =============================================================================
-- Нить — это незакрытое
-- =============================================================================
-- Начатое дело, неотправленное письмо, человек, с которым поссорился, вещь,
-- которую хочет, решение, которое откладывает. У нити два свойства, которых
-- нет у воспоминания: она ОТКРЫТА (у неё нет конца) и к ней МОЖНО ВЕРНУТЬСЯ.
--
-- Этого достаточно, чтобы путь развития складывался сам, без подсказки
-- автора: нить рождается из канона, к ней возвращаются или не возвращаются,
-- она закрывается или забывается. Вечерний проход видит открытые нити и
-- решает, что с ними стало сегодня, — и через месяц в биографии появляется
-- то, чего в ней не было: продолжение.
CREATE TABLE threads (
    id         BIGSERIAL PRIMARY KEY,

    -- Чья линия. **`user` объявлен и пока не пишется** — ровно так же, как
    -- `impulses_kind_ck` с Шага 35 объявил `anniversary`, у которого писатель
    -- появился только на Шаге 45. Механика у обеих сторон одна (открыть,
    -- вернуться, закрыть, забыть), а писатели разные: его линии ведёт
    -- вечерний проход, линии собеседника появятся с объектом №1.
    --
    -- Заводить под них вторую таблицу значило бы дважды написать одно и то же
    -- правило забывания и закрытия, а разъезжаются такие пары молча.
    side       TEXT        NOT NULL,

    -- Чем занят, словами персонажа. Одна фраза: нить — это не описание
    -- проекта, а то, что всплывает в голове само.
    text       TEXT        NOT NULL,

    opened_at  TIMESTAMPTZ NOT NULL,

    -- Когда к ней в последний раз возвращались. Двигается и при открытии, и
    -- при каждом упоминании в дневной сцене.
    --
    -- **Числа «жара» здесь нет намеренно.** Оно напрашивалось по образцу
    -- `impulses.urge`, но там накопление отвечает на вопрос «насколько тянет
    -- сказать», и у него есть читатель — порог инициативы. У нитей вопрос
    -- другой: какие три показать в промпте, когда открыто восемь. На него
    -- отвечает порядок, а порядок даёт `touched_at` без второй величины,
    -- которую пришлось бы пересчитывать и держать в согласии с ним.
    touched_at TIMESTAMPTZ NOT NULL,

    -- Закрыта или забыта. Разницу несёт `closed_why`, а не второй флаг.
    closed_at  TIMESTAMPTZ,
    closed_why TEXT,

    CONSTRAINT threads_side_ck   CHECK (side IN ('self', 'user')),
    CONSTRAINT threads_text_ck   CHECK (length(btrim(text)) > 0),
    CONSTRAINT threads_closed_ck CHECK (
        (closed_at IS NULL) = (closed_why IS NULL)
    )
);

-- Частичный индекс: читателя интересуют только открытые, а закрытых со
-- временем станет большинство. Порядок — свежесть возвращения, и он же
-- порядок показа в промпте.
CREATE INDEX threads_open_idx ON threads (side, touched_at DESC)
    WHERE closed_at IS NULL;

-- =============================================================================
-- Забывание
-- =============================================================================
-- Нить, к которой не возвращались три недели, закрывается сама, с пометкой
-- «забылось». Это не уборка мусора, а свойство предмета: люди бросают
-- начатое, и биография, в которой каждая начатая линия рано или поздно
-- доводится до конца, — не биография, а сюжет.
--
-- Закрывается, а не удаляется. Брошенное — такое же свидетельство, как
-- протухший импульс и несказанный повод: по нему потом будет видно, за что
-- персонаж брался и чего не доделал. Правило то же, что у `strongest_impulse`:
-- протухшее пропускают, но не стирают.
--
-- Модель для этого не зовётся: три недели тишины — арифметика, а не суждение.
