-- Инициатива: персонаж получает право заговорить первым (Шаг 35).
--
-- До этой миграции всё, что персонаж говорил, было ОТВЕТОМ: строка
-- `assistant` появлялась только парой к строке `user`, и на этом
-- предположении молча стояла половина чтений. Миграция ломает предположение
-- намеренно и потому идёт вместе с правкой читателей, а не впереди неё.

-- =============================================================================
-- Признак «сказал сам»
-- =============================================================================
-- Колонка, а не отдельная таблица, и не новая роль в `messages_role_ck`.
--
-- Роль отвергнута сразу: `role` уезжает в модель как есть
-- (`snapshot.message`), и третье значение пришлось бы отображать обратно в
-- `assistant` на каждом чтении — то есть завести отображение, обязанное
-- совпадать в четырёх местах. Для модели это ОДИН и тот же голос
-- персонажа; отличается не голос, а повод.
--
-- Отдельная таблица отвергнута по той же причине, по которой `self` живёт
-- объектом №0: реплика есть реплика, порядок у неё общий, и разложи её по
-- двум таблицам — `working_memory` пришлось бы собирать `UNION`ом с
-- сортировкой, а `id` перестал бы задавать порядок разговора.
--
-- DEFAULT FALSE — не осторожность, а совместимость с прошлым: всё, что
-- записано до этой миграции, было ответом, и `FALSE` про эти строки правда.
ALTER TABLE messages ADD COLUMN spontaneous BOOLEAN NOT NULL DEFAULT FALSE;

-- Частичный: спрашивают только про сказанное самим (бюджет суток и пауза
-- между репликами считаются по нему), а таких строк меньшинство.
CREATE INDEX messages_spontaneous_idx ON messages (ts DESC) WHERE spontaneous;

-- =============================================================================
-- Импульсы: повод заговорить, который копится
-- =============================================================================
-- **Побуждение накопительное, а не булево, и это несущее решение.** Булев
-- повод («погода сменилась — говори») даёт персонажа, который реагирует на
-- каждый чих и молчит, когда не случилось ничего конкретного. Копящееся
-- побуждение даёт другое: мелкие поводы складываются, крупные срабатывают
-- сразу, а молчание само по себе становится поводом, потому что растёт.
--
-- Величина `urge` безразмерная и правится на живом, как `RETRIEVER_COOLDOWN`.
-- Порог живёт в `cycle`, а не здесь: база хранит побуждение, решает — цикл.
CREATE TABLE impulses (
    id         BIGSERIAL   PRIMARY KEY,
    kind       TEXT        NOT NULL,
    -- О чём именно. Для погоды — семейство, для тишины — пусто. Нужен, чтобы
    -- два повода одного рода про разное не складывались в один: «начался
    -- дождь» и «пошёл снег» — разные новости.
    subject    TEXT,
    urge       REAL        NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL,
    -- Когда побуждение последний раз подливали. Не то же, что `created_at`:
    -- по нему считается затухание, иначе повод, возникший неделю назад и с
    -- тех пор не подтверждённый, ждал бы своего часа вечно.
    updated_at TIMESTAMPTZ NOT NULL,
    -- Срок годности новости. Погода протухает за часы, годовщина — за сутки.
    -- NULL — не протухает (тишина).
    expires_at TIMESTAMPTZ,
    spoken_at  TIMESTAMPTZ,
    CONSTRAINT impulses_kind_ck CHECK (kind IN (
        -- Живые сегодня:
        'silence',      -- давно не разговаривали
        'weather',      -- за окном сменилось семейство погоды
        -- Названы заранее, как `assertions.source = 'dream'` был назван до
        -- Фазы 7: место под них есть, кода пока нет.
        'curiosity',    -- незакрытый вопрос из прошлого разговора
        'anniversary',  -- годовщина эпизода
        'dream'         -- приснилось, хочет рассказать
    )),
    CONSTRAINT impulses_urge_ck CHECK (urge >= 0)
);

-- Открытый импульс на (род, предмет) РОВНО ОДИН — иначе побуждение не
-- копится, а размножается: каждый тик заводил бы новую строку «тишина», и
-- сотня слабых поводов никогда не собралась бы в один сильный.
--
-- `coalesce(subject, '')` — потому что NULL в уникальном индексе не
-- конфликтует сам с собой, а безпредметный повод (тишина) обязан быть один.
-- Тот же приём, что у `objects.label_norm <> ''`, только с обратным знаком.
CREATE UNIQUE INDEX impulses_open_uq
    ON impulses (kind, coalesce(subject, '')) WHERE spoken_at IS NULL;

-- Потребитель спрашивает только про несказанное и сортирует по силе.
CREATE INDEX impulses_pending_idx ON impulses (urge DESC) WHERE spoken_at IS NULL;
