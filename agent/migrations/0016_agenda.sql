-- Воля: он сам решает, чем занять время (Шаг 57).
--
-- До этой миграции у каждого занятия было своё расписание: чтение с 9 до 24
-- раз в шесть часов, эссе с 19 до 24 раз в сутки, новости раз в три часа.
-- Персонаж выбирал, ЧТО читать и О ЧЁМ писать, но не выбирал, читать ли
-- вообще, — это решали часы. Шаг 57 заводит один проход «чем заняться»,
-- который смотрит на побуждения, нити, настроение и сделанное за день и
-- выбирает действие. Расписания занятий уходят; у кода остаётся физиология:
-- ночь (сон), тишина (не во время разговора), интервал между решениями.

-- =============================================================================
-- Журнал выбранных дел
-- =============================================================================
-- **Пишется КАЖДОЕ решение, включая «ничего».** Отказ от дела — тоже выбор, и
-- по журналу должно быть видно, как он проводит время, а не только чем занят,
-- когда занят. Персонаж, который шесть заходов подряд выбирает «ничего», —
-- это состояние, и проход побуждений обязан его видеть.
--
-- **Дела, у которых уже есть свои таблицы (чтение, эссе, новости), здесь не
-- дублируются по содержанию.** Строка журнала говорит «решил читать, потому
-- что...», а что прочитано, лежит в `readings`. Связи ключом нет намеренно:
-- заход чтения может не состояться (полка пуста), и строка журнала при этом
-- остаётся правдой — он хотел.
CREATE TABLE pursuits (
    id        BIGSERIAL   PRIMARY KEY,
    at        TIMESTAMPTZ NOT NULL,
    action    TEXT        NOT NULL,
    -- Почему, ЕГО словами. Обязательно: решение без причины — это расписание,
    -- просто записанное задним числом.
    why       TEXT        NOT NULL,
    -- О чём, если у действия есть предмет: что искать, что вспоминать, о чём
    -- задуматься, о чём написать собеседнику.
    about     TEXT,
    -- Какое побуждение толкнуло. SET NULL, а не CASCADE: дело было, даже если
    -- побуждение потом закрыли.
    drive_id  BIGINT      REFERENCES drives(id) ON DELETE SET NULL,
    -- Что вышло, словами: что взял из найденного, что вспомнилось, куда ушла
    -- мысль. NULL — ничего не вышло или действие результата не имеет.
    outcome   TEXT,
    CONSTRAINT pursuits_action_ck CHECK (action IN (
        'read',      -- читать (заход `cycle.reading_tick`)
        'write',     -- писать своё (заход `essay.essay_tick`)
        'news',      -- глянуть новости (заход `news.news_tick`)
        'explore',   -- покопаться в сети в том, что не отпускает
        'recall',    -- вспоминать: биография растёт по его воле
        'daydream',  -- задуматься, уйти мыслью; в биографию НЕ пишется
        'reach',     -- захотелось написать собеседнику
        'rest'       -- ничего
    )),
    CONSTRAINT pursuits_why_ck CHECK (length(btrim(why)) > 0)
);
CREATE INDEX pursuits_at_idx ON pursuits (at DESC);

-- Метка решения. Двигается при каждом решении, включая «ничего»: интервал
-- считается от выбора, а не от дела — иначе «ничего» звало бы модель каждую
-- минуту (довод `agent.day_at`, 0009).
ALTER TABLE agent ADD COLUMN agenda_at TIMESTAMPTZ;

