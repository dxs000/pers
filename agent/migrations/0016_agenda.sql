--   pursuit  — сам покопался и что-то нашёл;
--   daydream — задумался, и мысль ушла туда, куда хочется рассказать;
--   reach    — просто захотелось написать, без внешнего повода.
-- `reach` не обходит заслонок: пишет он всё равно через `background_tick`.
