-- Обещание с точным сроком (Шаг 43).
--
-- До этой миграции на «напомни мне выпить таблетки через пять часов» персонаж
-- отвечал согласием и не напоминал. Записать пять часов было некуда:
-- `impulses_kind_ck` перечисляет пять родов, и `reminder` среди них нет — база
-- отказала бы. Единственная случайная тропинка вела через `linger`, который
-- мог счесть таблетки незакрытым вопросом и завести `curiosity` с TTL в 72
-- часа; тогда персонаж спрашивал про них в случайный момент ближайших трёх
-- суток, интонацией «а что там было», а не «пора».
--
-- Это худший из возможных исходов. Не «не умею» — а обещал и не сделал, и
-- отличить «забыл» от «не умеет» изнутри разговора нечем.
--
-- =============================================================================
-- Почему отдельная таблица, а не `kind = 'reminder'` в `impulses`
-- =============================================================================
-- Это главное решение шага, и оно конструктивное, а не вкусовое.
--
-- `impulses` — экономика ЖЕЛАНИЯ говорить. Поводы копятся (`record_urge`
-- прибавляет к накопленному), затухают со временем, конкурируют по `urge`,
-- глушатся на `IMPULSE_DAMP` после любой сказанной реплики и проходят три
-- заслонки: порог, паузу в два часа и потолок в шесть реплик в сутки. Всё это
-- правильно ровно потому, что там живут желания: ни одно из них не ОБЯЗАНО
-- прозвучать, и `0002_initiative.sql` написан целиком про то, как персонажу
-- не быть навязчивым.
--
-- Обещание — не желание, а долг. У него точное время, оно не копится, не
-- затухает и не конкурирует. Положи его в ту же таблицу — и смена погоды
-- (`WEATHER_URGE = 1.2`) сможет перебить напоминание по силе, а исчерпанный
-- бюджет суток проглотит его целиком. Причём проглотит МОЛЧА: в логе будет
-- «инициатива: бюджет суток исчерпан», и выглядеть это будет как штатная
-- работа заслонки, а не как несдержанное слово.
--
-- Тот же довод, по которому тишина не живёт в `impulses` (Шаг 37): в одной
-- таблице лежит одна порода величин. Там — накопительные события, здесь —
-- срочные долги. Общего у них только то, что и то и другое кончается
-- репликой.
--
-- =============================================================================
-- Чего здесь намеренно НЕТ
-- =============================================================================
-- Нет `urge`: обещание не бывает сильнее или слабее. Нет затухания: долг,
-- о котором не напомнили, не становится меньше. Нет `expires_at`: просроченное
-- обещание не протухает, а требует извинения — см. `repeats` ниже.
--
-- Нет и повторяемости («каждый день в девять»). Она не дописывается сюда
-- колонкой `rrule`: повторяющееся напоминание — это уже расписание, у него
-- своя жизнь (пропуски, паузы, отмена серии), и запихнутое в ту же строку оно
-- заставит каждый читатель различать два разных объекта. Понадобится —
-- заведётся своей таблицей, ссылающейся сюда.
CREATE TABLE promises (
    id         BIGSERIAL PRIMARY KEY,

    -- Когда пообещали и когда напомнить. Обе метки — TIMESTAMPTZ, как всё
    -- остальное в схеме: считает демон в UTC, рендерит в местном.
    created_at TIMESTAMPTZ NOT NULL,
    due_at     TIMESTAMPTZ NOT NULL,

    -- О чём напомнить, СЛОВАМИ СОБЕСЕДНИКА, а не пересказом персонажа.
    -- Пересказ здесь был бы тем же, чем `subject` у сна: обрезкой, у которой
    -- есть полный текст в другой таблице. У обещания другого хранилища нет,
    -- и переформулированное («что-то про лекарства») превращает напоминание в
    -- намёк.
    text       TEXT        NOT NULL,

    -- Откуда взялось. Не для целостности — для ответа на «с чего он взял».
    -- ON DELETE SET NULL, а не CASCADE: сессию когда-нибудь подберёт Curator,
    -- и обещание не должно исчезнуть вместе с разговором, в котором прозвучало.
    -- Долг переживает повод, по которому возник.
    message_id BIGINT      REFERENCES messages(id) ON DELETE SET NULL,

    -- Когда сказал в последний раз и сколько раз всего.
    --
    -- Два поля, а не одно: `said_at` отвечает «когда», `repeats` — «сколько»,
    -- и вывести одно из другого нельзя. Правило из `0002_initiative.sql` про
    -- флаг, дублирующий состояние, здесь не нарушается: это не флаг, а два
    -- разных наблюдения.
    said_at    TIMESTAMPTZ,
    repeats    INT         NOT NULL DEFAULT 0,

    -- Закрыто: либо собеседник отозвался после напоминания, либо попытки
    -- исчерпаны. Строка не удаляется — по ней потом будет видно, о чём
    -- персонажа просили и чем это кончилось. То же правило, что у протухших
    -- импульсов: свидетельство важнее чистоты таблицы.
    closed_at  TIMESTAMPTZ,

    CONSTRAINT promises_text_ck    CHECK (length(btrim(text)) > 0),
    CONSTRAINT promises_repeats_ck CHECK (repeats >= 0),

    -- Срок в прошлом — не «просроченное обещание», а сломанный разбор времени.
    -- Просрочка возникает ПОТОМ, когда демон лежал; в момент записи её быть не
    -- может. Ограничение стоит здесь именно затем, чтобы ошибка парсера
    -- («через 5 часов» превратилось во вчера) падала в писателе, а не всплывала
    -- напоминанием, которое срабатывает немедленно и выглядит помешательством.
    CONSTRAINT promises_due_ck     CHECK (due_at >= created_at)
);

-- Частичный индекс: читателя интересуют только открытые, а закрытых со
-- временем станет большинство. Условие то же по духу, что у
-- `impulses_open_uk`: незакрытая строка — единственная, до которой есть дело.
CREATE INDEX promises_due_idx ON promises (due_at) WHERE closed_at IS NULL;

-- Уникальности здесь НЕТ, в отличие от импульсов. Там частичный уникальный
-- индекс по (kind, subject) не давал завести второй повод об одном и том же —
-- и это верно для желаний, которые сливаются. Обещания не сливаются: «напомни
-- позвонить маме» в понедельник и то же самое в четверг — два разных долга с
-- двумя разными сроками, и схлопнуть их значило бы одно из них не выполнить.

-- =============================================================================
-- Как это читается
-- =============================================================================
-- `cycle.promise_tick` — отдельный заход, зовущийся ДО `background_tick` и
-- мимо его заслонок. Порядок в `agent.idle_tick` не косметический: сначала
-- долг, потом желание. Тот же по природе порядок, что «погода до заслонок, а
-- модель после» — сначала то, что нельзя потерять.
--
-- Специальной координации между заходами не понадобилось: напомнив, персонаж
-- зовёт `append_utterance`, и `background_tick` на том же круге увидит
-- `last_utterance` нулевой давности и промолчит по собственной паузе. Заслонка
-- инициативы сработала так, как и задумана: человек услышал реплику, и вторая
-- подряд ему не нужна.
--
-- Подтверждением считается ЛЮБОЙ ответ собеседника после напоминания
-- (`agent.last_exchange_ts > said_at`), а не слово «принял». Различать
-- «выпил» и «прочитал» пришлось бы моделью, то есть заводить ещё один проход
-- ради вопроса, ответ на который персонажу и не нужен: он напоминает, а не
-- надзирает.
