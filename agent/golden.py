PROMISE_ASKED = NOW                                   # когда попросили
PROMISE_DUE = NOW + timedelta(hours=5)                # «через пять часов»
PROMISE_ON_TIME = PROMISE_DUE + timedelta(minutes=2)  # заход вовремя
PROMISE_REPEAT = PROMISE_ON_TIME + timedelta(hours=1)  # повтор: ответа не было
PROMISE_LATE = PROMISE_DUE + timedelta(hours=4)       # заход после простоя

# Ответ писателя собирается из констант, а не вписан строкой: местное время
# считается от `NOW_REF`, и вписанная строка разошлась бы с ним молча при
# первом же сдвиге опорного момента.
