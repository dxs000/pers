#   модель — `_StubLLM`, пять ответов ПО ПОРЯДКУ ВЫЗОВОВ.
#
# Порядок — не деталь реализации заглушки, а то, ради чего сценарий и
# написан. Ярлык («ретривер», «ответчик», …) приходит из ожиданий сбруи, а
# не из разбора промпта: переставь ход вызовы местами — и в эталоне ярлык
# встанет напротив чужого промпта, видимой строкой.


def _head(text: str, limit: int = 52) -> str:
    """Первые символы промпта в одну строку — отпечаток, а не копия.

    Целиком класть незачем: пять промптов уже лежат эталонами по
    отдельности, и дублировать их здесь значило бы перерезать два файла
    на каждую правку `mind`.
    """
    flat = " ".join((text or "").split())
    return flat if len(flat) <= limit else flat[:limit] + "…"


def _journal_line(label: str, what: str, text: str) -> str:
    """Строка журнала: ярлык, что уехало, ДЛИНА и начало.

    Длина здесь не для красоты. Начало промпта у экстрактора одинаково с
    находками и без них — первые полсотни символов это шапка рубрики, — и
    отвались блок найденного по дороге, отпечаток из одного `_head` этого
    бы не показал. Длина показывает: у `extractor` и `extractor_web`
    эталоны разного размера, и разница ровно в том блоке.
    """
    return f"{label:<12} | {what:<10} | {len(text):>5} симв | «{_head(text)}»"


class _StubLLM:
    """Модель, отвечающая по списку. Лишний вызов — падение, а не молчание.

    Молчаливая заглушка («кончились ответы — верну пустое») превратила бы
    изменение числа проходов в тихо иной эталон. Здесь это `AssertionError`
    с именем: сбруя обязана падать там, где перестала понимать программу.
    """

    def __init__(self, script, journal):
        self._script = list(script)
        self._journal = journal
        # Всё, что ход показал модели. Нужен ровно один вызов — ответчик, —
        # но узнаётся он по СОДЕРЖИМОМУ (единственный с системной ролью), а
        # не по номеру: номер сделал бы артефакт слепым к перестановке.
        self.seen: list[list[dict]] = []
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self._create))

    def retarget(self, journal) -> None:
        """Писать дальше в другой журнал. Скрипт продолжается с того же места.

        Нужно из-за расщепления хода на T1 и T2 (Шаг 27): единицы разные, и
        в артефакте они обязаны быть разными списками, — но модель между
        ними одна, и счёт её вызовов сквозной.
        """
        self._journal = journal

    def _create(self, *, model=None, messages=None, **kwargs):
        if not self._script:
            raise AssertionError(
                "сбруя: модель позвана больше раз, чем в сценарии — "
                f"лишний промпт: «{_head((messages or [{}])[-1].get('content', ''))}»"
            )
        label, reply = self._script.pop(0)
        self.seen.append(list(messages or []))
        last = (messages or [{}])[-1].get("content", "")
        self._journal.append(
            _journal_line(label, f"{len(messages or [])} сообщ.", last)
        )
        return SimpleNamespace(
            choices=[SimpleNamespace(message=SimpleNamespace(content=reply))]
        )


