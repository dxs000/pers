def _dump_threads(eng) -> str:
    rows = eng.all_threads()
    if not rows:
        return "нити: нет"
    out = ["нити:",
           f"  {'№':<3} | {'сторона':<6} | {'возвращались':<26} | "
           f"{'закрыта':<10} | текст"]
    for r in rows:
        out.append(f"  {r['id']:<3} | {r['side']:<6} | {r['touched_at']:<26} | "
                   f"{(r['closed_why'] or '—'):<10} | {r['text'][:60]}")
    return "\n".join(out)


def _run_day() -> str:
    """День пишется вперёд: заслонки, сверка, метка после пустого.

    Артефактов пять, и каждый закрывает свой стык:

    - **промпт дня** — целиком. В нём видны черты (которых у сна нет
      намеренно), вчерашняя сцена и прямой запрет писать разговор с
      собеседником. Последнее не украшение: разговор часто единственное
      заметное в дне, и без запрета канон удваивался бы двумя писателями;
    - **шесть заходов** — три молчащих и три работающих. Заслонки неразличимы
      поодиночке: «не вечер» и «уже подводили» выглядят одинаково;
    - **две сверки рядом** — записать и противоречит. Прожитое противоречить
      МОЖЕТ, в отличие от приснившегося, и ворота у него общие с биографом;
    - **канон до и после** — одна сцена из двух, с источником `lived`;
    - **метка после пустого дня** — то, ради чего колонка. В `memories` после
      пятого захода не появляется ничего, и отличить «спросили и ответили
      ничего» от «не спрашивали» можно только по ней.
    """
    eng = open_engine()
    net = _FakeNet()
    journal: list[str] = []
    llm = _StubLLM(_DAY_SCRIPT, journal)
    edges = cycle.Edges(llm=llm, http=net, search=net, search_key="ключ-заглушка")

    before = _dump_memories(eng)

    steps = []

    def run(at, title):
        got = cycle.day_tick(eng, edges, at, tz=TZ)
        steps.append(f"{title}: вернул = {got!r}, метка = {iso(eng.day_at())}")
        return got

    run(DAY_NOON, "полдень (17:00 по месту)")

    # Тишина: разговор десять минут назад. Метку двигает `touch_exchange` —
    # та же, что в бою двигает T1.
    with eng.unit():
        eng.touch_exchange(DAY_EVENING - timedelta(minutes=10))
    run(DAY_EVENING, "вечер, говорили 10 мин назад")

    with eng.unit():
        eng.touch_exchange(DAY_EVENING - timedelta(hours=3))
    run(DAY_EVENING, "вечер, тихо три часа")
    prompt = llm.seen[0][0]["content"]
    run(DAY_EVENING + timedelta(hours=1), "тот же вечер, +1 ч")

    run(DAY_NEXT, "следующий вечер: вернулся к нити 1, закрыл нить 2")
    threads_after = _dump_threads(eng)

    # Три недели спустя. Нить 1 последний раз трогали в прошлый заход, и к
    # этому вечеру она перевалила за `THREAD_FORGET_DAYS` — закроется сама,
    # без модели. Вечерний проход при этом состоится: пустой день тоже день.
    run(DAY_NEXT + timedelta(days=22), "через 22 дня, день пуст")

    return (
        f"ПРОМПТ ДНЯ:\n{prompt}\n"
        f"{'=' * 60}\n"
        f"окно вечера: {cycle.DAY_HOUR_FROM}:00-{cycle.DAY_HOUR_TO}:00 по месту, "
        f"тишина {cycle.DAY_QUIET_HOURS} ч, не чаще {cycle.DAY_INTERVAL_HOURS} ч\n"
        + "\n".join(steps)
        + f"\n{'=' * 60}\n"
        f"вызовы модели по порядку:\n"
        + "\n".join(f"{i}. {line}" for i, line in enumerate(journal, 1))
        + f"\n{'=' * 60}\n"
        f"канон ДО:\n{before}\n"
        f"канон ПОСЛЕ:\n{_dump_memories(eng)}\n"
        f"{'=' * 60}\n"
        f"нити после второго вечера:\n{threads_after}\n"
        f"нити после третьего (забывание через {cycle.THREAD_FORGET_DAYS:.0f} "
        f"дней):\n{_dump_threads(eng)}"
    )


