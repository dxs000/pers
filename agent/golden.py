"""Золотой промпт: сбруя регрессии для сборки промпта.

Родилась сбруей ПАРИТЕТА (3b): два движка хранилища, один фикстур, и
требование сойтись побайтно. Ту работу она сделала — переезд в Postgres
нельзя было объявить состоявшимся на глаз, и он был объявлен диффом.

С Шага 26 движок один, и сверяются не движки друг с другом, а **выдача с
эталоном на диске**. Роль от этого не уменьшилась, а сменилась: артефакты
в истории репозитория ловят изменение промпта, которого никто не хотел, —
и ловят его на восемнадцати сценариях сразу, за одну команду.

Что здесь есть:
    - набор СЦЕНАРИЕВ: состояние + параметры рендера, замороженные так,
      чтобы промпт не зависел ни от часов, ни от сети, ни от окружения;
    - `--write` — записать эталоны в `golden/`;
    - `--check` — собрать заново и сдиффать с эталонами (exit 1 при
      расхождении, годится для CI и для pre-commit).

**Три источника недетерминизма и что с каждым сделано:**
    1. Часы. Всё «сейчас» — от `build_fixture.NOW_REF`, ни одного
       `datetime.now()`.
    2. Часовой пояс. НЕ `config.TZ`: она читается из `.env` и на другой
       машине другая, а эталон обязан совпадать между машинами. Пояс
       прибит здесь константой `TZ` — фикстур живёт в Тбилиси, UTC+4.
    3. Сеть. Погода — замороженный слепок (`_WEATHER_*`), находки —
       замороженный список. Небо НЕ заморожено: `sky.snapshot` — чистая
       офлайн-арифметика, и настоящий вызов детерминирован при
       фиксированных координатах и `NOW_REF`. Так в эталон попадает
       вся цепочка `sky` → `_render_sky`, а не заглушка вместо неё.

**Про движки.** Флага `--engine` больше нет: словарь из одного ключа
проверял бы движок против самого себя. Шов, ради которого модуль писался
до переезда, свою работу отработал дважды — впустил `pg` и выпустил
`json`.

**Фикстур перестал быть состоянием.** До Шага 26 его читала
`store.load_state`, то есть как состояние работающей программы; теперь
это данные для заливки, и читает их `build_fixture.load()`. Сбруя не
трогает JSON вовсе: `_SYSTEM`/`_SERVICE` получают снимок и движок, а
буфер выжимки приезжает из `eng.summary_buffer()` — до Шага 26 он на
pg-прогоне брался из файла, единственное место, где сбруя ходила мимо
базы.

Что каждый сценарий держит под током (по одному читателю на сценарий):
    base      — память, self, эпизоды, возраст, `source`-метки. Базовая
                регрессия Шага 15.
    outside   — латч среды: `sky` живой + погода-заглушка ДРУГОГО семейства,
                чем в латче фикстура → срабатывает `_outside_changes`.
                Единственное место, где проверяется `agent.outside_latch`.
    silence   — `_render_silence`: `last_exchange` отодвинут на 300 часов.
                В открытой сессии эта ветка не срабатывает никогда, поэтому
                нужен отдельный сценарий.
    findings  — блок «глянул в сеть», непустой.
    nothing   — он же при `findings=[]` («искали, не нашли»). Отличие от
                `None` — смысловое, и оно должно быть видно в эталоне.
    empty     — чистый старт: ровно то, что персонаж отрендерит в первую
                минуту жизни на пустой базе.
    memory    — рабочая память, поднятая из хранилища (Шаг 24), и тот же
                обмен в транскрипте выжимки. Ответ длиннее `TEXT_LIMIT`,
                поэтому эталон показывает решение шага: в памяти целиком,
                в промпте обрезано.
    turn      — провод хода (Шаг 27): порядок вызовов, момент отдачи
                ответа, что читается до записи. Два хода, потому что
                состояние МЕЖДУ ходами одним не проверяется.
    inbox     — очередь (Шаг 28): разрез пачки по разрыву сессии, склейка,
                две формы времени, три терминальных состояния строки
                `inbox` и гонка двух потребителей, разыгранная по шагам.
    client    — протокол клиента (Шаг 29): три состояния своей реплики,
                включая отсутствующую строку.
    inspector — читающая сторона инспектора (Шаг 30): семь выдач, которые
                Фаза 4a отдаст браузером, и доказательство, что читаются
                они соединением, которым база не даёт писать.
    http      — транспорт (Шаг 31): маршрут ведёт к своей выдаче, параметры
                разбираются, отказы различимы, соединение закрывается. Тел
                ответов тут нет — вместо копии `inspector.txt` печатается
                вердикт сверки с прямым вызовом.
"""

