def _run_traits() -> str:
    """Черты выводятся из канона и замещают прежние.

    Артефактов пять, и каждый закрывает свой стык:

    - **промпт черт** — целиком. В нём виден весь канон, нынешние черты и
      требование основания под каждую. Требование основания — единственное,
      что отделяет проход от анкеты, и подмена промпта видна только здесь;
    - **черты с основаниями** — то, что вернула модель. Основания в базу не
      едут (колонки под них нет), но в лог едут, и артефакт обязан показывать,
      что проход их спрашивал;
    - **было -> стало** — замещение. Из фикстурных трёх две ушли, и уход
      обязан быть видимым: слияние вместо замены выглядело бы здесь как
      успешная запись;
    - **второй заход** — молчит: канон с первого захода не вырос. Метка
      сдвинута, шаг не набран;
    - **первая строка системного промпта** — то, ради чего всё. Черты живут
      не в базе, а вот в этой строке, и она обязана собраться из нового
      списка.
    """
    eng = open_engine()
    net = _FakeNet()
    journal: list[str] = []
    llm = _StubLLM(_TRAITS_SCRIPT, journal)
    edges = cycle.Edges(llm=llm, http=net, search=net, search_key="ключ-заглушка")

    before = eng.snapshot(TRAITS_NOW).traits
    canon = eng.all_memories()
    grown = eng.memories_since(eng.traits_at())

    got = cycle.reconsider_traits(eng, edges, TRAITS_NOW)
    after = eng.snapshot(TRAITS_NOW)
    # Второй заход СРАЗУ, а не через сутки: порог накопительный, и время в
    # нём не участвует вовсе. Прогони мы его позже, сценарий проверял бы
    # выдержку, которой у прохода нет.
    again = cycle.reconsider_traits(eng, edges, TRAITS_NOW + timedelta(days=2))

    return (
        f"ПРОМПТ ЧЕРТ:\n{llm.seen[0][0]['content']}\n"
        f"{'=' * 60}\n"
        f"канон: {len(canon)} строк, новых с прошлого пересчёта: {grown} "
        f"(шаг {cycle.TRAITS_STEP}, пол {cycle.TRAITS_FLOOR})\n"
        f"{'=' * 60}\n"
        f"вызовы модели по порядку:\n"
        + "\n".join(f"{i}. {line}" for i, line in enumerate(journal, 1))
        + f"\n{'=' * 60}\n"
        f"было:  {', '.join(before) or '(не было)'}\n"
        f"стало: {', '.join(after.traits) or '(не записано)'}\n"
        f"вернул проход: {got}\n"
        f"{'=' * 60}\n"
        f"заход 2 (канон не вырос): {again}\n"
        f"новых с пересчёта: {eng.memories_since(eng.traits_at())}\n"
        f"{'=' * 60}\n"
        f"история черт (Шаг 56 — основания больше не выбрасываются):\n"
        f"{_dump_trait_history(eng)}\n"
        f"{'=' * 60}\n"
        "первая строка системного промпта:\n"
        + build_system_prompt(after, TRAITS_NOW.astimezone(TZ)).split("\n\n")[0]
    )


