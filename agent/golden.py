def _canonical(turn) -> str:
    """Снимок -> канонный JSON. Артефакт сценариев записи.

    `sort_keys=False` намеренно: порядок полей в снимке значим (он доезжает
    до промпта через `json.dumps` в рефлекторе), и сортировка ключей
    спрятала бы ровно тот класс расхождений, который ловили на Шаге 17.
    """
    return json.dumps(asdict(turn), ensure_ascii=False, indent=2)


def _run_writes() -> str:
    """Прогнать скрипт записи через фасад и вернуть снимок после него."""
    eng = open_engine()
    with eng.unit():
        for kind, payload in _WRITE_SCRIPT:
            if kind == "object":
                eng.upsert_object(payload, WRITE_NOW)
            else:
                eng.merge_self_assertions(payload, WRITE_NOW)
    return _canonical(eng.snapshot(WRITE_NOW))


def _run_session() -> str:
    """Прогнать сессию через фасад и сдать ДВА артефакта разом.

    Артефакта два, потому что проверяются две разные вещи: промпт выжимки
    (что суммаризатор увидел, включая предупреждение об отрезанном начале)
    и снимок после закрытия (что осело эпизодом). Порознь они пропустили бы
    друг друга: промпт не покажет `exchanges` эпизода, снимок не покажет
    транскрипт.
    """
    texts = [f"реплика номер {i}" for i in range(_SESSION_EXCHANGES)]
    answers = [f"ответ номер {i}" for i in range(_SESSION_EXCHANGES)]

    eng = open_engine()
    for i in range(_SESSION_EXCHANGES):
        at = WRITE_NOW + timedelta(minutes=i)
        with eng.unit():
            eng.append_exchange(texts[i], answers[i], at)
            eng.touch_exchange(at)

    turn = eng.snapshot(WRITE_NOW)
    buffer = eng.summary_buffer()
    stale = eng.session_stale(WRITE_NOW + timedelta(hours=4))
    prompt = _build_summarizer_prompt(turn, buffer)
    with eng.unit():
        episode = eng.close_session(WRITE_NOW, "выжимка-заглушка")
    after = eng.snapshot(WRITE_NOW)

    return (
        f"{prompt}\n"
        f"{'=' * 60}\n"
        f"session_stale(+4ч) = {stale}\n"
        f"эпизод: {json.dumps(episode, ensure_ascii=False, sort_keys=True)}\n"
        f"{'=' * 60}\n"
        f"{_canonical(after)}"
    )


def _run_memory() -> str:
    """Рабочая память после обмена — и тот же обмен глазами выжимки.

    Смотрит на то, чего не показывает ни один из тринадцати: **содержание
    реплик**, поднятых из хранилища. Снимок сюда не смотрит вовсе —
    разговор в него не входит по устройству (вход хода, а не память).

    Фикстур приезжает с открытой сессией на три обмена (`dropped: 3`),
    четвёртый дописывается здесь. Значит в эталоне видно и продолжение
    чужого разговора, и порядок ролей, и то, что предел в сорок обменов на
    четырёх не срабатывает.
    """
    eng = open_engine()
    with eng.unit():
        eng.append_exchange(_MEMORY_USER, _MEMORY_ANSWER, WRITE_NOW)
        eng.touch_exchange(WRITE_NOW)

    memory = eng.working_memory()
    prompt = _build_summarizer_prompt(eng.snapshot(WRITE_NOW), eng.summary_buffer())

    return (
        f"working_memory: {len(memory)} сообщений\n"
        f"{json.dumps(memory, ensure_ascii=False, indent=2)}\n"
        f"{'=' * 60}\n"
        f"{prompt}"
    )


@dataclass(frozen=True)
class _Driven:
    """Что вернул прогон одного хода. Семь значений кортежем не читаются.

    Полей семь, потому что ход с Шага 27 — это ДВЕ единицы, и артефакт
    показывает обе: `journal` — вызовы T1, `digest` — вызовы T2,
    `digested` — нашлась ли для T2 работа вообще.
    """

    outcome: object
    journal: list[str]
    messages: list[dict]
    before: object
    after: object
    digest: list[str]
    digested: bool


def _drive_turn(eng, net, script, text, now):
    """Один ход под заглушками.

    Возвращает (итог, журнал, что уехало в модель, заслонка до, заслонка после).

    **Заслонка ретривера читается из базы, а не подаётся параметром.** До
    Шага 33 её возил счётчик `since_search`: сбруя передавала его в
    `handle_turn`, а `Outcome` возвращал следующее значение. Правка «поиск
    по времени» перенесла заслонку в `agent.last_search_ts` — её читает
    `look_outward` через `eng.last_search_ts()` и пишет `eng.mark_search()`,
    — и параметра не стало. Артефакт от этого не обеднел, а стал честнее:
    счётчик был свойством вызова и жил ровно столько, сколько длился ход, а
    метка — свойство персонажа и переживает перезапуск. Смотреть на неё надо
    там, где она лежит.
    """
    journal: list[str] = []
    llm = _StubLLM(script, journal)
    edges = cycle.Edges(llm=llm, http=net, search=net, search_key="ключ-заглушка")

    before = eng.last_search_ts()
    outcome = cycle.handle_turn(
        eng, edges, text, now,
        announce=lambda answer: journal.append(
            _journal_line("ОТВЕТ", "человеку", answer)
        ),
        tz=TZ,
    )
    after = eng.last_search_ts()

    # T2 ОТДЕЛЬНЫМ вызовом, и журнал у него свой. `handle_turn` больше не
    # переваривает: он кладёт работу в `followups` и возвращается, а три
    # служебных прохода делает `digest_one` — так демон и работает
    # (`agent.drain` зовёт его, когда очередь пуста). Пока T2 шёл внутри
    # хода, сбруя видела шесть вызовов подряд и не могла отличить «ответ
    # отдан до переваривания» от «отдан после»; теперь разделение
    # структурное, и артефакт показывает его двумя списками, а не порядком
    # строк в одном. Ровно то же решение, что у `announce`: границу видно
    # там, где она есть.
    # Заглушка ОДНА на обе единицы, меняется только журнал, в который она
    # пишет. Второй `_StubLLM` со срезом скрипта развязал бы их и потерял
    # главное свойство первой: «позвана больше раз, чем в сценарии — падение».
    # С одной заглушкой лишний вызов в T1 съедает ответ, предназначенный T2,
    # и краснеет там, где случился, а не там, где кончился срез.
    digest: list[str] = []
    llm.retarget(digest)
    digested = cycle.digest_one(eng, edges, now)

    messages = next((m for m in llm.seen if m and m[0]["role"] == "system"), None)
    if messages is None:
        raise AssertionError("сбруя: ход не показал модели ни одного системного промпта")
    return _Driven(outcome, journal, messages, before, after, digest, digested)


def _search_ts(value) -> str:
    """`last_search_ts` для артефакта. Нет метки — прочерк, а не `None`.

    Прочерк, потому что «персонаж ещё не искал ни разу» — законное
    состояние чистого старта, а не пропущенное значение, и выглядеть оно
    должно как состояние.
    """
    return "—" if value is None else iso(value)


def _numbered(lines) -> str:
    return "\n".join(f"{i}. {line}" for i, line in enumerate(lines, 1))


def _render_turn(title: str, d: _Driven) -> str:
    layers = "\n".join(
        f"[{i}] {m['role']}\n{m['content']}" for i, m in enumerate(d.messages, 1)
    )
    # Переход метки И есть видимая заслонка: сдвинулась — поиск состоялся,
    # осталась прежней — подавлен. Печатается переход, а не факт поиска,
    # потому что факт выводится из перехода, а обратное неверно.
    moved = "сдвинулась" if d.before != d.after else "не двигалась"
    # Списка два, и это структура артефакта, а не оформление. Одним списком
    # «ответ отдан ДО переваривания» доказывалось бы порядком строк, то есть
    # соглашением; двумя — доказывается тем, что T1 закончился.
    return (
        f"{title}: ответ есть = {d.outcome.answer is not None}, "
        f"ошибка = {d.outcome.error}, "
        f"last_search_ts: {_search_ts(d.before)} -> {_search_ts(d.after)} "
        f"({moved})\n"
        f"{'=' * 60}\n"
        f"уехало в модель ({len(d.messages)} сообщений):\n{layers}\n"
        f"{'=' * 60}\n"
        f"T1 — вызовы по порядку (ответ отдан здесь):\n{_numbered(d.journal)}\n"
        f"{'-' * 60}\n"
        f"T2 — отложенное переваривание, работа нашлась = {d.digested}:\n"
        f"{_numbered(d.digest)}"
    )


def _run_turn() -> str:
    """Прогнать ЦЕЛЫЙ ход и сдать четыре артефакта разом.

    Четыре, потому что провод ломается на стыках, а каждый срез в
    отдельности стык пропускает:

    - **что уехало в модель** — три слоя вместе: системный промпт (с
      находками и средой), рабочая память из хранилища, реплика. Порознь
      слои покрыты, их сборка — нет;
    - **порядок вызовов** — включая строку `announce`: она стоит между
      ответчиком и тремя служебными проходами и доказывает, что человек
      не ждёт их секунд. Уедет печать к вызывающему — строка уйдёт из
      эталона;
    - **снимок хранилища после хода** — что записали T1 и T2: настроение,
      self-факт, сматченная Анна, новый объект с меткой `web`, латч среды,
      переписанный дождём;
    - **рабочая память после хода** — доказательство T1: две строки,
      реплика и ответ, в правильном порядке и с правильными ролями.

    Первый ход застаёт заслонку ОТКРЫТОЙ: фикстур приезжает без
    `last_search_ts` (персонаж ещё не искал), и `look_outward` пропускает
    запрос. Второй ход отстоит меньше чем на `RETRIEVER_COOLDOWN_HOURS`,
    поэтому заслонка закрыта, и находок нет ни в системном промпте, ни у
    экстрактора — при том что ретривер всё равно спрошен.

    **Интервал между ходами задан заслонкой, и это правка Шага 33.** Пока
    заслонка была счётчиком-параметром, интервал ни на что не влиял и стоял
    в два часа; с переездом в `agent.last_search_ts` она стала временной, и
    два часа при пороге в час означали бы, что заслонка успела открыться
    обратно. Ветка подавления — ровно то, что правка «поиск по времени»
    изменила, и остаться непроверенной она не может.

    Цена названа: на получасовом интервале молчание короче
    `SILENCE_MIN_HOURS`, и строки «Прошлый разговор был…» во втором промпте
    больше нет. Потеря невелика — ветку молчания держит свой сценарий
    (`silence`), у которого разрыв в 300 часов, — но она есть, и удержать
    обе одним прогоном нельзя: пороги смотрят в разные стороны от одного
    часа. Обратная ветка (заслонка открылась снова, поиск повторился) сегодня
    не покрыта; ей нужен третий ход, и это отдельное решение со своей ценой
    в четыреста строк эталона.
    """
    eng = open_engine()
    net = _FakeNet()

    first = _drive_turn(eng, net, _TURN_SCRIPT_1, _TURN_USER, TURN1_NOW)
    second = _drive_turn(eng, net, _TURN_SCRIPT_2, _TURN2_USER, TURN2_NOW)

    return (
        f"{_render_turn('ход 1', first)}\n"
        f"{'=' * 60}\n"
        f"{_render_turn('ход 2 (+30 мин)', second)}\n"
        f"{'=' * 60}\n"
        f"рабочая память после двух ходов:\n"
        f"{json.dumps(eng.working_memory(), ensure_ascii=False, indent=2)}\n"
        f"{'=' * 60}\n"
        f"{_canonical(eng.snapshot(TURN2_NOW))}"
    )


def _dump_inbox(eng) -> str:
    """Таблица `inbox` целиком, включая помеченное.

    Читается напрямую, а не через фасад, и это решение: у фасада этих
    состояний нет — `pending()` по устройству показывает только
    непомеченное, а метод ради артефакта был бы методом, которого не зовёт
    ни ход, ни демон. Артефакт смотрит на ТАБЛИЦУ, и это честнее:
    терминальные состояния объявлены схемой, схему он и показывает.

    **С Шага 30 читающий контракт у них появился** (`inspector.queue`), и
    дамп всё равно остаётся сырым — намеренно. Сценарий очереди проверяет
    ход, а не инспектора, и подставь сюда чтение инспектора, обе стороны
    сломались бы согласованно и молча. Расхождение между таблицей и
    контрактом ловит сценарий `inspector`, у которого своя половина.
    """
    rows = eng.conn.execute(
        "SELECT id, ts, text, handled_at, reply_id FROM inbox ORDER BY id"
    ).fetchall()
    out = [f"{'id':>2} | {'пришло':<25} | {'помечено':<25} | reply_id | текст"]
    for r in rows:
        out.append(
            f"{r['id']:>2} | {r['ts'].isoformat():<25} | "
            f"{(r['handled_at'].isoformat() if r['handled_at'] else '—'):<25} | "
            f"{(str(r['reply_id']) if r['reply_id'] else '—'):<8} | {r['text']}"
        )
    return "\n".join(out)


def _dump_messages(eng) -> str:
    """Все строки `messages` с сессией и меткой времени.

    Ради этого артефакта сценарий и написан наполовину: **две формы времени
    видны только здесь**. У строки `user` — момент, когда человек договорил;
    у `assistant` — когда персонаж ответил. Слейся они в одну, дифф покажет
    это одной колонкой.
    """
    rows = eng.conn.execute(
        "SELECT id, session_id, ts, role, text FROM messages ORDER BY id"
    ).fetchall()
    out = [f"{'id':>2} | сес | {'ts':<25} | {'роль':<9} | текст"]
    for r in rows:
        out.append(f"{r['id']:>2} | {r['session_id']:>3} | {r['ts'].isoformat()} | "
                   f"{r['role']:<9} | {_head(r['text'], 60)}")
    sessions = eng.conn.execute(
        "SELECT id, dropped, closed_at, episode_id FROM sessions ORDER BY id"
    ).fetchall()
    out.append("")
    out.append("сессии: " + "; ".join(
        f"#{s['id']} dropped={s['dropped']} "
        f"{'закрыта -> ep_' + str(s['episode_id']) if s['closed_at'] else 'открыта'}"
        for s in sessions))
    return "\n".join(out)


def _run_inbox() -> str:
    """Очередь -> ход, целиком: разрез, склейка, две формы времени, гонка.

    Артефактов шесть, и каждый закрывает свой стык:

    - **разрез пачки** — что признано этим разговором, а что прошлым;
    - **порядок вызовов** — где в нём стоит закрытие сессии. Оно обязано
      случиться ПОСЛЕ прибавки счёта отброшенного и ДО хода: `close_session`
      считает длину эпизода как «обмены + dropped», и переставь эти двое
      местами — потерянные реплики не попадут в эпизод вовсе;
    - **таблица `inbox`** — три терминальных состояния разом: непомеченное,
      помеченное с общим `reply_id` (склеенные — ответ у них один) и
      помеченное без него (прочитано поздно, ответа не будет);
    - **таблица `messages`** — две формы времени и счётчик `dropped`;
    - **эпизод** — что осело от прошлого разговора вместе с потерянными;
    - **гонка** — второй потребитель на той же пачке. Он доходит до T1,
      получает пустую пометку и уходит ни с чем: ни строки в `messages`, ни
      следа в `inbox`.
    """
    eng = open_engine()
    net = _FakeNet()
    journal: list[str] = []

    with eng.unit():
        for ts, text in zip(INBOX_TS, INBOX_TEXTS):
            eng.push(text, ts)

    # Что увидит разрез — считается ДО прогона, иначе после пометки
    # `pending()` вернёт пусто и показывать будет нечего.
    batch = cycle.split_batch(eng.pending())

    closed: list = []

    def _close():
        """Колбэк закрытия сессии. У сбруи он без выжимки и без печати.

        `main.finish_session` сюда не зовётся намеренно: он сетевой (просит
        у модели выжимку) и печатающий, а сценарий проверяет ГРАНИЦУ —
        что колбэк позван, и позван в правильном месте. Та же развязка, что
        у `announce`, и по той же причине.
        """
        with eng.unit():
            episode = eng.close_session(INBOX_NOW, "выжимка-заглушка")
        journal.append(_journal_line("СЕССИЯ", "закрыта",
                                     json.dumps(episode, ensure_ascii=False,
                                                sort_keys=True)))
        closed.append(episode)
        return episode

    llm = _StubLLM(_INBOX_SCRIPT, journal)
    outcome = cycle.handle_pending(
        eng, cycle.Edges(llm=llm, http=net, search=net, search_key="ключ-заглушка"),
        INBOX_NOW,
        announce=lambda answer: journal.append(
            _journal_line("ОТВЕТ", "человеку", answer)),
        close_session=_close,
        tz=TZ,
    )

    after_first = (
        f"разрез пачки: этот разговор {batch.ids}, прошлый "
        f"{[r['id'] for r in batch.stale]}\n"
        f"договорил в: {batch.arrived_at.isoformat()}\n"
        f"склеенная реплика:\n{batch.text}\n"
        f"{'=' * 60}\n"
        f"итог: ответ есть = {outcome.answer is not None}, "
        f"ошибка = {outcome.error}, перехвачен = {outcome.superseded}, "
        f"last_search_ts -> {_search_ts(eng.last_search_ts())}\n"
        f"{'=' * 60}\n"
        f"вызовы по порядку:\n"
        + "\n".join(f"{i}. {line}" for i, line in enumerate(journal, 1))
        + f"\n{'=' * 60}\n{_dump_inbox(eng)}"
        f"\n{'=' * 60}\n{_dump_messages(eng)}"
        # Эпизод целиком, а не отпечатком из журнала: `exchanges` — это и
        # есть «счёт остаётся». Обрежь его `_head`, как строку журнала, и
        # поломка «прибавили после закрытия» перестала бы быть видна там,
        # где она смысловая.
        f"\nэпизод прошлого разговора: "
        f"{json.dumps(closed[0] if closed else None, ensure_ascii=False, sort_keys=True)}"
    )

    # --- Вторая половина: две копии потребителя на одной пачке -------------
    # Демона ещё нет, а путь уже есть: `systemd` перезапустил юнит, старый
    # не умер. Разыгрывается по шагам — оба берут пачку, оба считают ответ,
    # первый успевает пометить. Проверяется не предположение, а поведение.
    with eng.unit():
        eng.push(INBOX_RACE_TEXT, INBOX_RACE_TS)

    shared = eng.pending()
    race_journal: list[str] = []
    winner = cycle.handle_turn(
        eng, cycle.Edges(llm=_StubLLM(_INBOX_WINNER_SCRIPT, race_journal),
                         http=net, search=net, search_key="ключ-заглушка"),
        INBOX_RACE_TEXT, INBOX_RACE_NOW,
        arrived_at=INBOX_RACE_TS,
        inbox_ids=[r["id"] for r in shared], tz=TZ,
    )
    loser = cycle.handle_turn(
        eng, cycle.Edges(llm=_StubLLM(_INBOX_RACE_SCRIPT, race_journal),
                         http=net, search=net, search_key="ключ-заглушка"),
        INBOX_RACE_TEXT, INBOX_RACE_NOW + timedelta(seconds=1),
        arrived_at=INBOX_RACE_TS,
        inbox_ids=[r["id"] for r in shared], tz=TZ,
    )

    return (
        f"{after_first}\n"
        f"{'=' * 60}\n"
        f"ГОНКА: пачка {[r['id'] for r in shared]} взята дважды\n"
        f"первый:  ответ есть = {winner.answer is not None}, "
        f"перехвачен = {winner.superseded}\n"
        f"второй:  ответ есть = {loser.answer is not None}, "
        f"перехвачен = {loser.superseded}\n"
        f"{'=' * 60}\n{_dump_inbox(eng)}"
        f"\n{'=' * 60}\n{_dump_messages(eng)}"
    )


def _seed_queue(eng) -> tuple[int, int, int]:
    """Догнать очередь до трёх терминальных состояний. Возвращает их id.

    Один посев на два сценария: `client` смотрит, что покажет оболочка,
    `inspector` — что покажет страница. Правило состояний одно (Шаг 30,
    `inspector.inbox_state`), и посев обязан быть один: разойдись он, и два
    артефакта проверяли бы разные очереди, называя это одной.

    Состояния догоняются ТЕМИ ЖЕ вызовами, какими это делает ход, — обменом
    и пометкой. Выдумать их присвоением было бы проще и доказывало бы
    только то, что читатель умеет читать колонки, которые сам и заполнил.
    """
    with eng.unit():
        waiting = eng.push("а это я только что написал", INBOX_NOW)
        answered = eng.push("а это уже с ответом", INBOX_NOW)
        dropped = eng.push("а это опоздало", INBOX_NOW)

    with eng.unit():
        reply_id = eng.append_exchange("а это уже с ответом",
                                       "Отвечаю, как и обещал.", INBOX_NOW)
        eng.mark_handled([answered], INBOX_NOW, reply_id)
        eng.mark_handled([dropped], INBOX_NOW)

    return waiting, answered, dropped


# Пять объектов сверх четырёх фикстурных — намеренно, чтобы их стало ДЕВЯТЬ
# и предел снимка (семь) начал связывать. На четырёх он не связывает: все,
# кроме «кофе», проходят и порог, и предел, а значит отметка `in_prompt`,
# посчитанная по снимку, и отметка, пересчитанная по одному порогу,
# неотличимы — проверено внесением. С девятью «Набоков» выпадает из промпта,
# оставаясь выше порога, и разница между «слишком тускл» и «нашлось семь
# ярче» становится видна строкой. Тот же приём, что у `_SESSION_EXCHANGES`,
# который на единицу больше предела выжимки.
#
# Метки времени разнесены на 12 часов, чтобы порядок по эффективной
# важности был устойчив и не решался ничьими.
_INSPECT_SEED = [
    ("place", "Нарикала", "fact", "крепость над старым городом", 1),
    ("place", "Мтацминда", "fact", "гора с парком и фуникулёром", 13),
    ("thing", "хинкали", "preference", "ест руками и не спорит об этом", 25),
    ("topic", "Руставели", "fact", "проспект, а не только поэт", 37),
    ("thing", "фуникулёр", "fact", "работает до полуночи", 49),
]


def _seed_inspector():
    """Фикстур плюс девять объектов и очередь в трёх состояниях.

    Один посев на два сценария — тем же доводом, что у `_seed_queue`
    (Шаг 30): `inspector` смотрит, ЧТО читается из базы, `http` (Шаг 31) —
    ЧЕМ это доезжает до браузера, и сверяет тело ответа с прямым вызовом.
    Сверка имеет смысл, только если оба смотрят на одну базу; разойдись
    посев — и вердикт «тело совпадает» доказывал бы совпадение двух разных
    состояний, то есть ничего.
    """
    eng = open_engine()
    for otype, label, key, value, hours_ago in _INSPECT_SEED:
        with eng.unit():
            eng.upsert_object(
                {"type": otype, "label": label,
                 "assertions": [{"key": key, "value": value,
                                 "confidence": "high", "source": "user"}]},
                NOW - timedelta(hours=hours_ago),
            )
    _seed_queue(eng)
    return eng


def _run_inspector() -> str:
    """Читающая сторона инспектора (Шаг 30): всё, что уедет в 4a.

    Артефактов восемь, и семь из них — то, что Express отдаст как JSON.
    Восьмой — доказательство, что читает он тем соединением, которым писать
    нельзя.

    **Читается ВСЁ через read-only соединение**, открытое рядом с пишущим.
    Это единственный сценарий сбруи, где соединений два, и второе тут не для
    полноты: свойство «инспектор не пишет» проверяется только попыткой
    записи, а попытка записи с пишущего соединения проверяла бы обратное.
    Печатается класс исключения и SQLSTATE, а не текст ошибки: текст
    локализуется настройкой сервера (`lc_messages`), и эталон, зависящий от
    неё, разошёлся бы между машинами — источник недетерминизма ровно того
    рода, что уже дважды ловил переезд (пояс базы, локаль базы).

    Очередь досевается до трёх состояний, потому что пустая таблица в
    эталоне означала бы «читатель не проверен», а не «читателю нечего
    показать».
    """
    import inspector

    eng = _seed_inspector()

    ro = inspector.connect(test=True)
    try:
        blocks = [
            "ОБЗОР\n" + json.dumps(inspector.overview(ro, NOW),
                                   ensure_ascii=False, indent=2),
            "ОБЪЕКТЫ (все, не только доехавшие до промпта)\n"
            + json.dumps(inspector.objects(ro, NOW), ensure_ascii=False, indent=2),
            # Объект №0 и Анна: между ними разыграны обе причины отсечки —
            # `low` не проходит фильтр доверия, `med` не влезает в предел.
            # Остальные три объекта фикстура молчаливы (по одному-два факта,
            # все проходят), и класть их в эталон значило бы удлинить его,
            # ничего не проверив.
            "ФАКТЫ объекта №0 (self)\n"
            + json.dumps(inspector.facts(ro, 0), ensure_ascii=False, indent=2),
            "ФАКТЫ объекта 1\n"
            + json.dumps(inspector.facts(ro, 1), ensure_ascii=False, indent=2),
            "ЭПИЗОДЫ\n" + json.dumps(inspector.episodes(ro),
                                     ensure_ascii=False, indent=2),
            "СЕССИИ\n" + json.dumps(inspector.sessions(ro),
                                    ensure_ascii=False, indent=2),
            "РАЗГОВОР открытой сессии\n"
            + json.dumps(inspector.conversation(ro, 1), ensure_ascii=False, indent=2),
            "ОЧЕРЕДЬ\n" + json.dumps(inspector.queue(ro),
                                     ensure_ascii=False, indent=2),
            _render_inspector_prompt(inspector.prompt(ro, NOW, TZ)),
            _render_read_only(ro),
        ]
    finally:
        # Закрыть обязательно: соединение, оставленное открытым, доживёт до
        # `TRUNCATE` следующего сценария и встанет с ним на блокировке —
        # ровно то замирание прогона, из-за которого точка открытия движка
        # в сбруе одна (см. `open_engine`).
        ro.close()

    return f"\n{'=' * 60}\n".join(blocks)


def _render_inspector_prompt(page: dict) -> str:
    """Промпт страницы — отпечатком, а не копией.

    Целиком он тут лежать не может: это тот же промпт, что в `base.txt`, и
    два файла, обязанные совпадать, пришлось бы перерезать на каждую правку
    `mind`. Тот же довод, по которому журнал хода печатает `_head` вместо
    промптов. Но одного `_head` мало — начало у всех системных промптов
    одинаково, — поэтому печатаются ДЛИНА и заголовки блоков: пропади из
    памяти эпизоды или объекты, исчезнет строка, а не пять символов.
    """
    parts = page["text"].split("\n\n")
    lines = [f"ПРОМПТ на {page['as_of']} — {len(page['text'])} симв, "
             f"{len(parts)} блоков"]
    lines += [f"  [{i}] {_head(p, 60)}" for i, p in enumerate(parts, 1)]
    lines.append("чего в нём нет:")
    lines += [f"  - {c}" for c in page["caveats"]]
    return "\n".join(lines)


def _render_read_only(ro) -> str:
    """Доказательство, что писать этим соединением нельзя.

    Не «инспектор не вызывает UPDATE» — это проверяется чтением кода и
    ломается следующей правкой, — а «база отказала». Проверка идёт после
    всех чтений: под autocommit неудавшийся стейтмент не портит соединение,
    но порядок всё равно такой, чтобы поломка проверки не могла объясниться
    испорченным соединением.
    """
    import psycopg

    alive = ro.execute("SELECT count(*) AS n FROM objects").fetchone()["n"]
    try:
        ro.execute("UPDATE agent SET mood = 'подменено инспектором' WHERE id = 1")
        verdict = "ЗАПИСЬ ПРОШЛА — соединение не read-only"
    except psycopg.Error as err:
        verdict = f"запись отклонена базой: {type(err).__name__}, SQLSTATE {err.sqlstate}"
    return (f"ЧЕМ ЧИТАЕТ\nчтение работает: строк в objects (вместе с №0) = "
            f"{alive}\n{verdict}")


# --- Сценарий HTTP (Шаг 31) --------------------------------------------------
# Седьмое семейство. Смотрит на транспорт и только на транспорт: маршрут,
# статус, тип содержимого, разбор параметров, коды отказа.
#
# **Тел ответов в эталоне нет, и это решение.** Положи их — и файл стал бы
# копией `golden/inspector.txt`, обязанной совпадать с ним побайтно, то есть
# ровно тем, что проект вычистил уже пять раз. Вместо копии печатается
# ВЕРДИКТ: сценарий зовёт инспектора напрямую тем же соединением и
# сравнивает байты с телом ответа. Так эталон транспорта не двигается,
# когда меняется содержание страниц, — и краснеет, когда маршрут начинает
# отдавать не ту выдачу или не в той форме.
#
# Тот же приём, что у `_render_inspector_prompt` (отпечаток вместо промпта),
# только доведённый до конца: там сравнивать было не с чем, здесь есть.
_HTTP_AT = NOW + timedelta(hours=24)


def _wsgi(app, path: str, query: str = "", method: str = "GET"):
    """Позвать приложение БЕЗ сокета. Возвращает (статус, заголовки, тело).

    Сокет тут был бы третьим источником недетерминизма после часов и сети:
    свободный порт, время подъёма, таймаут клиента. WSGI-приложение —
    вызываемый объект, и в этом половина довода, по которому шаг выбрал
    WSGI, а не собственный `http.server`.
    """
    captured = {}

    def start_response(status, headers):
        captured["status"] = status
        captured["headers"] = dict(headers)

    body = b"".join(app(
        {"REQUEST_METHOD": method, "PATH_INFO": path, "QUERY_STRING": query},
        start_response,
    ))
    return captured["status"], captured["headers"], body


def _run_http() -> str:
    """HTTP-контур инспектора (Шаг 31): чем выдачи доедут до браузера.

    Проверяются четыре вещи, и ни одна из них не про содержание страниц:

    1. **Маршрут ведёт к своей выдаче.** Вердикт «тело == прямой вызов»
       краснеет, если `/api/objects` начнёт отдавать эпизоды или если
       форма ответа разойдётся с формой артефакта (`indent`, `ensure_ascii`).
    2. **Параметры разбираются, а не игнорируются.** `?at=` сверяется с
       вызовом инспектора на ДРУГОЙ момент: игнорируй его вид — и вердикт
       станет «НЕТ», потому что совпало бы с `NOW`, а не с `at`.
    3. **Отказы различимы.** 404 на опечатке в пути, 405 на методе, 400 на
       каждом из двух параметров — восемь строк. Тела печатаются целиком:
       они короткие, стабильные и их читает человек с `curl`.
    4. **Соединение закрывается.** Не «мы вызываем close», а счётчик:
       открыто столько же, сколько закрыто. Соединение, пережившее запрос,
       встанет с `TRUNCATE` следующего сценария — то самое замирание
       прогона, из-за которого точка открытия движка в сбруе одна. Тот же
       счётчик показывает, что отказы до базы не доходят вовсе.

    Плюс проба записи на ПЕРВОМ соединении приложения. Свойство «инспектор
    не пишет» доказано на Шаге 30 для своего соединения; здесь доказывается,
    что вид открывает такое же, а не своё пишущее.

    **Цена названа, и она меньше, чем кажется:** двенадцать рукопожатий с
    базой — по одному на УДАВШИЙСЯ запрос. Семь отказов соединения не
    открывают вовсе: 404 решается маршрутом, 405 методом, 400 разбором
    параметров, и до `connect()` дело не доходит. Счётчик это и меряет —
    начни вид открывать соединение до разбора, и двенадцать стали бы
    девятнадцатью. Переиспользовать соединение сбруи нельзя, не убив
    четвёртую проверку: подсунь приложению общее с пустым `close`, и
    счётчик закрытых стал бы измерять заглушку.
    """
    import httpd
    import inspector
    import psycopg
    from urllib.parse import urlencode

    _seed_inspector()

    opened = []
    probe = []

    def _connect():
        conn = inspector.connect(test=True)
        opened.append(conn)
        if not probe:
            try:
                conn.execute("UPDATE agent SET mood = 'подменено видом' WHERE id = 1")
                probe.append("ЗАПИСЬ ПРОШЛА — вид открывает пишущее соединение")
            except psycopg.Error as err:
                probe.append(f"запись отклонена базой: {type(err).__name__}, "
                             f"SQLSTATE {err.sqlstate}")
        return conn

    app = httpd.build_app(connect=_connect, clock=lambda: NOW, tz=TZ)
    ro = inspector.connect(test=True)

    def _same(body: bytes, expected) -> str:
        want = (json.dumps(expected, ensure_ascii=False, indent=2) + "\n").encode("utf-8")
        return "да" if body == want else "НЕТ"

    # Пары «запрос — прямой вызов». Вызов ленив (lambda), иначе он случился
    # бы до запроса и на другом состоянии базы.
    cases = [
        ("/api/overview", "", "inspector.overview(NOW)",
         lambda: inspector.overview(ro, NOW)),
        ("/api/objects", "", "inspector.objects(NOW)",
         lambda: inspector.objects(ro, NOW)),
        ("/api/objects", urlencode({"at": _HTTP_AT.isoformat()}),
         "inspector.objects(NOW+24ч)", lambda: inspector.objects(ro, _HTTP_AT)),
        ("/api/objects/0/facts", "", "inspector.facts(0)",
         lambda: inspector.facts(ro, 0)),
        ("/api/objects/1/facts", "", "inspector.facts(1)",
         lambda: inspector.facts(ro, 1)),
        ("/api/episodes", "", "inspector.episodes()",
         lambda: inspector.episodes(ro)),
        ("/api/episodes", "limit=2", "inspector.episodes(2)",
         lambda: inspector.episodes(ro, 2)),
        ("/api/sessions", "", "inspector.sessions()",
         lambda: inspector.sessions(ro)),
        ("/api/sessions/1/messages", "", "inspector.conversation(1)",
         lambda: inspector.conversation(ro, 1)),
        ("/api/queue", "", "inspector.queue()",
         lambda: inspector.queue(ro)),
        ("/api/prompt", "", "inspector.prompt(NOW)",
         lambda: inspector.prompt(ro, NOW, TZ)),
    ]

    lines = ["МАРШРУТЫ"]
    for path, query, label, call in cases:
        status, headers, body = _wsgi(app, path, query)
        shown = f"{path}?{query}" if query else path
        lines.append(f"GET {shown:<44} | {status:<8} | {headers['Content-Type']} "
                     f"| тело == {label}: {_same(body, call())}")

    # Отказы. Тела целиком: короткие, стабильные, и читать их человеку.
    refusals = [
        ("GET", "/api/nope", "", "опечатка в пути"),
        ("GET", "/api/objects/abc/facts", "", "id не число — маршрута нет"),
        ("POST", "/api/overview", "", "метод; заголовок Allow обязателен"),
        # Восьмой отказ — не для полноты, а против конкретной перестановки:
        # проверь метод РАНЬШЕ пути, и опечатка в адресе получала бы 405
        # вместо 404, то есть «сюда так нельзя» вместо «такого адреса нет».
        # Без этой строки поломка не ловилась бы ничем: `POST /api/overview`
        # остаётся 405 при любом порядке проверок.
        ("POST", "/api/nope", "", "метод на несуществующем пути — 404, а не 405"),
        ("GET", "/api/prompt", urlencode({"at": "не-дата"}), "at не разбирается"),
        ("GET", "/api/prompt", urlencode({"at": "2026-01-15T09:00:00"}),
         "at без пояса — момент неоднозначен"),
        ("GET", "/api/episodes", "limit=abc", "limit не число"),
        ("GET", "/api/episodes", "limit=0", "limit не положительный"),
    ]
    blocks = ["\n".join(lines)]
    out = ["ОТКАЗЫ"]
    for method, path, query, why in refusals:
        status, headers, body = _wsgi(app, path, query, method)
        shown = f"{path}?{query}" if query else path
        allow = f" | Allow: {headers['Allow']}" if "Allow" in headers else ""
        out.append(f"{method} {shown:<48} | {status}{allow}   ({why})")
        out.append("\n".join("    " + ln for ln in body.decode().rstrip().splitlines()))
    blocks.append("\n".join(out))

    # Объект, которого нет: 200 и пустой список, а не 404. Решение названо в
    # `httpd._facts` и стоит в эталоне строкой, потому что менять его —
    # значит менять контракт, а не поведение.
    status, _, body = _wsgi(app, "/api/objects/999/facts")
    blocks.append("ОБЪЕКТА НЕТ\nGET /api/objects/999/facts | " + status + "\n"
                  + body.decode().rstrip())

    blocks.append(
        f"СОЕДИНЕНИЯ\nоткрыто {len(opened)}, закрыто "
        f"{sum(1 for c in opened if c.closed)}\n{probe[0]}"
    )
    ro.close()
    return f"\n{'=' * 60}\n".join(blocks)


def _run_client() -> str:
    """Читающая половина клиента: что он видит в каждом состоянии.

    **Единственная часть Шага 29, которую сбруя держит по устройству.**
    Всё остальное там — форма процесса: петля, сигналы, юнит; они
    однопоточностью и детерминизмом не проверяются и уходят в чек-лист
    руками. А вот протокол клиента — чистое чтение трёх состояний строки
    `inbox`, и оно проверяется без процесса вовсе.

    Состояния берутся не выдуманные: сценарий догоняет `inbox` до каждого
    из них теми же вызовами, какими это делает ход, — обменом и пометкой.
    Выдумать их присвоением было бы проще и доказывало бы только то, что
    `read_state` умеет читать колонки, которые сам же и заполнил.
    """
    import cli

    eng = open_engine()

    # Три реплики, по одной на состояние: первую не тронем, вторая получит
    # ответ, третья — пометку без ответа (так уходят реплики по ту сторону
    # разрыва сессии). Посев общий с `inspector` — см. `_seed_queue`.
    waiting, answered, dropped = _seed_queue(eng)

    lines = [f"{'строка':>7} | {'состояние':<9} | что покажет клиент"]
    for label, inbox_id in (("ждём", waiting), ("ответ", answered),
                            ("опоздала", dropped)):
        state, payload = cli.read_state(eng.conn, inbox_id)
        lines.append(f"{inbox_id:>7} | {state:<9} | {payload!r}   ({label})")

    # Несуществующая строка — отдельный случай, и он не теоретический:
    # клиент переживает перезапуск базы, а `--reset` уносит очередь вместе
    # со всем. Ответ обязан быть «ждём», а не падением: подождать и уйти по
    # таймауту здесь честнее, чем уронить оболочку человеку в лицо.
    state, payload = cli.read_state(eng.conn, 999)
    lines.append(f"{999:>7} | {state:<9} | {payload!r}   (строки нет вовсе)")

    return "\n".join(lines) + (
        f"\n{'=' * 60}\n{_dump_inbox(eng)}"
    )


def render(name: str) -> str:
    """Собрать артефакт сценария. Ни часов, ни сети, ни `.env` — только база."""
    if name not in SCENARIOS:
        raise KeyError(name)

    if name == "http":
        return _run_http()
    if name == "inspector":
        return _run_inspector()
    if name == "client":
        return _run_client()
    if name == "inbox":
        return _run_inbox()
    if name == "turn":
        return _run_turn()
    if name == "memory":
        return _run_memory()
    if name == "session":
        return _run_session()
    if name in _WRITES:
        return _run_writes()

    if name in _EMPTY_SCENARIOS:
        return build_system_prompt(_fresh_engine().snapshot(NOW),
                                   NOW.astimezone(TZ))

    # Одна ветка вместо развилки на движок. Раньше здесь стояло условие,
    # в котором и был весь смысл 3b: JSON отдавал состояние, из которого
    # снимок собирал `store`, Postgres отдавал снимок сразу. Смысл
    # исчерпан — состояния как словаря в проекте больше нет вовсе.
    eng = open_engine()
    turn = eng.snapshot(NOW)

    if name in _SERVICE:
        # Служебные проходы часов не видят вовсе — ни `now`, ни среды.
        # Это свойство кода, а не сбруи, и эталон его фиксирует.
        text = _SERVICE[name](turn, eng)
        return "" if text is None else text

    params = _SYSTEM[name](eng)
    return build_system_prompt(
        turn,
        NOW.astimezone(TZ),
        params.get("sky"),
        params.get("weather"),
        params.get("last_exchange"),
        params.get("findings"),
    )


def _path(name: str) -> Path:
    return GOLDEN_DIR / f"{name}.txt"


def cmd_write(names: list[str]) -> int:
    GOLDEN_DIR.mkdir(exist_ok=True)
    for name in names:
        text = render(name)
        # newline="\n" — не педантизм. По умолчанию текстовая запись
        # переводит "\n" в os.linesep, и эталон, записанный на Windows,
        # лёг бы на диск с CRLF. Чтение его же обратно вернуло бы "\n"
        # (универсальные переводы строк), так что сверка бы прошла, — но
        # артефакт объявлен ПОБАЙТНЫМ, а git на переезде показал бы
        # изменившимся весь файл целиком. Прибиваем LF на обеих сторонах.
        _path(name).write_text(text + "\n", encoding="utf-8", newline="\n")
        print(f"записан {_path(name).relative_to(BASE_DIR)} ({len(text)} симв)")
    return 0


def cmd_check(names: list[str]) -> int:
    failed = []
    for name in names:
        path = _path(name)
        if not path.exists():
            print(f"НЕТ ЭТАЛОНА: {name} — сначала `golden.py --write`")
            failed.append(name)
            continue

        # Сравниваем БАЙТЫ, а не текст. Через текстовое чтение CRLF,
        # подсунутый git'ом на переезде (`core.autocrlf`), схлопнулся бы
        # в LF и молча совпал. Проверка объявлена побайтной — значит
        # побайтной на обеих сторонах. Заодно снимается зависимость от
        # `read_text(newline=...)`, которого нет до Python 3.13.
        expected = path.read_bytes()
        actual = (render(name) + "\n").encode("utf-8")

        if actual == expected:
            print(f"ok   {name}")
            continue

        failed.append(name)
        print(f"РАСХОЖДЕНИЕ  {name}")
        if b"\r\n" in expected and b"\r\n" not in actual:
            print("  (в эталоне CRLF, а собрано с LF — похоже на core.autocrlf; "
                  "см. .gitattributes)")
        diff = difflib.unified_diff(
            expected.decode("utf-8").splitlines(keepends=True),
            actual.decode("utf-8").splitlines(keepends=True),
            fromfile=f"эталон/{name}",
            tofile=f"собрано/{name}",
        )
        sys.stdout.writelines(diff)
        print()

    if failed:
        print(f"\nрасхождений: {len(failed)} из {len(names)} — {', '.join(failed)}")
        return 1
    print(f"\nвсе {len(names)} сценариев совпали побайтно")
    return 0


def cmd_show(names: list[str]) -> int:
    for name in names:
        print(f"{'=' * 70}\n{name}\n{'=' * 70}")
        print(render(name))
        print()
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Золотой промпт: сверка сборки промпта с эталонами.",
    )
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="сверить с эталонами (режим по умолчанию)")
    mode.add_argument("--write", action="store_true", help="перезаписать эталоны")
    mode.add_argument("--show", action="store_true", help="напечатать промпт в stdout")
    parser.add_argument("names", nargs="*", default=None,
                        help=f"сценарии; по умолчанию все: {', '.join(SCENARIOS)}")
    args = parser.parse_args()

    names = args.names or list(SCENARIOS)
    unknown = [n for n in names if n not in SCENARIOS]
    if unknown:
        parser.error(f"неизвестный сценарий: {', '.join(unknown)}")

    # Четыре строки после `finally` тут были недостижимы — наследство от
    # правки, добавившей закрытие соединения. Сняты заодно: мёртвый код
    # читается как ветка, которой не бывает.
    try:
        if args.write:
            return cmd_write(names)
        if args.show:
            return cmd_show(names)
        return cmd_check(names)
    finally:
        if _PG_ENGINE is not None:
            _PG_ENGINE.close()


if __name__ == "__main__":
    sys.exit(main())
