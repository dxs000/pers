_PG_ENGINE = None


def _shared_pg():
    """Единственное соединение сбруи. Открывается один раз на прогон."""
    global _PG_ENGINE
    if _PG_ENGINE is None:
        import engine as engine_mod

        _PG_ENGINE = engine_mod.PgEngine(test=True)
    return _PG_ENGINE


def open_engine():
    """Движок, заряженный фикстуром. Сбруя ходит в хранилище ТОЛЬКО отсюда.

    «Только отсюда» — не стиль, а условие работоспособности. Пока точек
    открытия было две (наследство от наложившихся правок), в процессе жило
    два соединения, и `TRUNCATE` следующего сценария намертво вставал на
    блокировке предыдущего. Прогон замирал ровно на границе чтения и
    записи, не показывая ни ошибки, ни строки.

    Это не удобство, а условие проверки. До Шага 20 сбруя ходила в `store`
    и `store_pg` напрямую, и фасад между ними оставался единственным
    непроверенным местом на пути от базы до промпта — ровно тот стык, на
    котором проект спотыкался трижды. С тех пор путь от базы до промпта
    проверен целиком, включая фасад, и с Шага 26 другого пути нет вовсе:
    состояния мимо движка сбруя не читает.

    Фикстур заливается на каждый вызов: прогон не должен зависеть от того,
    что осталось от прошлого.
    """
    import store_pg

    # Соединение переиспользуется на весь прогон, фикстур перезаливается
    # на каждый сценарий. Раньше открывалось и то и другое по 13 раз, и
    # прогон упирался в минуты: 13 рукопожатий с базой ради работы,
    # которой на секунду. Изоляция сценариев при этом не страдает —
    # её даёт `load_fixture` с его TRUNCATE, а не новый сокет.
    store_pg.load_fixture(_shared_pg().conn, build_fixture.load())
    return _PG_ENGINE


def sky_snapshot(eng) -> dict | None:
    """Небо на NOW из координат фикстура. Настоящий вызов программы.

    До Шага 27 здесь стояла КОПИЯ `main.sky_snapshot`, и докстринг честно
    сознавался: «повторяет». Копия, обязанная совпадать с оригиналом, —
    ровно тот шаблон, который проект вычистил дважды на Шаге 26 (формула
    затухания, досев объекта №0), и третий экземпляр жил в самой сбруе,
    то есть в инструменте, который такие вещи и должен ловить.

    Теперь зовётся настоящая функция — с Шага 32 это `sky.local_snapshot`,
    и место приезжает в неё параметром. Повторяются два `.get`, а не
    расчёт: цена того, что небо перестало ходить в фасад, и та же пара
    стоит в `prompt_and_latch` и в инспекторе. Пояс приходит параметром, а
    не из `config.TZ`: эталон обязан совпадать на машине, где `.env`
    другой, — источник недетерминизма №2.
    """
    place = eng.place()
    return sky.local_snapshot(place.get("lat"), place.get("lon"), NOW, TZ)


