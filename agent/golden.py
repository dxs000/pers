def _run_mood() -> str:
    """Настроение обретает причину, давность и право не меняться.

    Артефактов пять, и каждый закрывает свой стык:

    - **промпт настроения** — целиком. В нём видно нынешнее состояние с
      давностью и причиной и сказано, что несмена — самый частый ответ.
      Подмена вопроса («каким стало» вместо «изменилось ли») видна только
      здесь, и именно она была причиной эха;
    - **три захода** — смена, несмена, смена без причины. Средний обязан не
      двигать `mood_since`: в этом вся инерция, и в снимке она выглядит как
      бездействие, неотличимое от незвавшегося прохода;
    - **метка после каждого** — рядом с журналом вызовов. Порознь ни то ни
      другое ничего не доказывает;
    - **строка промпта в трёх возрастах** — свежая, суточной давности и
      выцветшая. Пометка давности берётся из своего словаря, и то, что она
      не совпадает с `AGE_BUCKETS`, видно только рядом;
    - **первая строка системного промпта при выцветшем** — то, ради чего всё.
      Блок обязан выпасть целиком, а не подставить «нейтральное»: подстановка
      выглядела бы исправной записью.
    """
    eng = open_engine()
    net = _FakeNet()
    journal: list[str] = []
    llm = _StubLLM(_MOOD_SCRIPT, journal)

    steps = []
    prompt = None
    for i, (ask, answer) in enumerate(_MOOD_EXCHANGES):
        turn = eng.snapshot(MOOD_NOW)
        found = mind.reflect_mood(turn, ask, answer, llm, now=MOOD_NOW)
        if prompt is None:
            prompt = llm.seen[0][0]["content"]
        if found:
            with eng.unit():
                eng.set_mood(found[0], found[1], MOOD_NOW + timedelta(minutes=i))
        after = eng.snapshot(MOOD_NOW)
        steps.append(
            f"заход {i + 1}: вернул = {found!r}\n"
            f"  стало: {after.mood!r}, отчего: {after.mood_reason!r}, "
            f"с: {after.mood_since}")

    # Рендер в трёх возрастах. Снимок один и тот же — меняется только `now`,
    # потому что возраст настроения есть свойство МОМЕНТА ЧТЕНИЯ, а не записи.
    turn = eng.snapshot(MOOD_NOW)
    ages = []
    for at, title in [(MOOD_NOW + timedelta(minutes=10), "свежее (+10 мин)"),
                      (MOOD_NOW + timedelta(hours=10), "держится (+10 ч)"),
                      (MOOD_LATER, f"выцвело (+40 ч при пороге "
                                   f"{mind.MOOD_FADE_HOURS} ч)")]:
        ages.append(f"{title}: {mind._render_mood(turn, at)!r}")

    faded = build_system_prompt(turn, MOOD_LATER).splitlines()[0]

    return (
        f"ПРОМПТ НАСТРОЕНИЯ (обмен 1):\n{prompt}\n"
        f"{'=' * 60}\n"
        + "\n".join(steps)
        + f"\n{'=' * 60}\n"
        f"вызовы модели по порядку:\n"
        + "\n".join(f"{i}. {line}" for i, line in enumerate(journal, 1))
        + f"\n{'=' * 60}\n"
        f"СТРОКА НАСТРОЕНИЯ в трёх возрастах:\n"
        + "\n".join(ages)
        + f"\n{'=' * 60}\n"
        f"первая строка системного промпта при выцветшем:\n{faded}"
    )


# --- Сценарий ОБЕЩАНИЙ (Шаг 43) ---------------------------------------------
# Тринадцатое семейство. Единственная в проекте реплика, которую персонаж
# ОБЯЗАН сказать: всё остальное, что он говорит по своей воле, имеет право не
# прозвучать. Отсюда и набор артефактов — они проверяют не «сработало ли», а
# «сработало ли, когда всё остальное молчит».
#
# Времена разнесены так, чтобы каждое состояние напоминания было отдельным
# заходом. Одним не обойтись: вовремя, с опозданием и повтор различаются
