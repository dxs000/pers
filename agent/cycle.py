def handle_turn(eng, edges: Edges, text: str, now: datetime, *,
                since_search: int = RETRIEVER_COOLDOWN,
                announce: Callable[[str], None] | None = None,
                arrived_at: datetime | None = None,
                inbox_ids: list[int] | tuple = (),
                tz=None) -> Outcome:
    """Один ход целиком: от реплики до записанных выводов.

    Порядок внутри — не последовательность удобства, а решения Шагов 22–24,
    и он тут перечислен потому, что менять его придётся ещё не раз:

    1. Снимок — ретриверу нужны метки объектов.
    2. Ретривер (сеть) — **до** ответа: он на критическом пути по существу.
    3. `previous` — до T1 и после ретривера. Строго до: `touch_exchange`
       перепишет `last_exchange_ts`, и разрыв мерился бы от самого себя.
    4. Промпт (плюс латч), рабочая память из хранилища, реплика — три слоя,
       и ни один не переживает ход.
    5. Ответ модели.
    6. **T1** — обмен И пометка очереди, одним коммитом. Запись раньше
       отдачи наружу: человек, не увидевший реплику, переспросит; персонаж,
       не помнящий своей реплики, выглядит беспамятным.
    7. `announce` — ответ уезжает наружу. Между ним и человеком не должно
       стоять трёх служебных вызовов.
    8. Снимок заново: между тем, что ушло в промпт, и тем, что видят
       служебные проходы, встал сам обмен.
    9. Три прохода — считаются ДО открытия T2 и ничего не пишут:
       транзакция не переживает вызов LLM.
    10. **T2** — осмысление одной единицей.

    Ошибка модели на шаге 5 — это `Outcome` с `error`, а не исключение:
    ход не состоялся, но процесс продолжается, и решать, что показать
    человеку, будет тот, у кого есть чем показывать. Латч к этому моменту
    уже записан — так было и до шага, и это не потеря: латч не память, а
    «что было за окном в прошлый раз».

    **Что при этом происходит с очередью, названо вслух, потому что в
    роадмапе этот случай не значился вовсе.** Ход упал до T1 — значит
    пометки не было, строки остались непомеченными, и следующая пачка
    возьмёт их снова и склеит с тем, что человек допишет. Слова не
    теряются, а «ответ выбрасывается» из комментария схемы описывает
    другой случай — гонку двух потребителей, а не отказ модели.
    """
    turn = eng.snapshot(now)

    findings, searched = look_outward(text, turn.objects, edges, since_search, now)
    since_search = 0 if searched else since_search + 1

    # Читается КАЖДЫЙ ход, а не один раз за процесс. Разница видна только у
    # долгоживущего процесса — и ровно поэтому её не было видно до сих пор.
    previous = eng.last_exchange()

    try:
        messages = (
            [{"role": "system",
              "content": prompt_and_latch(eng, edges, now, previous, findings, tz)}]
            + eng.working_memory()
            + [{"role": "user", "content": text}]
        )
        response = edges.llm.chat.completions.create(
            model=config.DEEPSEEK_MODEL,
            messages=messages,
        )
    except OpenAIError as err:
        return Outcome(answer=None, since_search=since_search, error=str(err))

    answer = response.choices[0].message.content

    # --- T1: обмен ------------------------------------------------------
    # С Шага 28 внутри T1 появилась третья запись — пометка очереди. Она
    # обязана идти ТЕМ ЖЕ коммитом, что и строки `messages` (решение Шага
    # 22): порознь «обработано» и «записано» разъедутся, и разойтись они
    # могут в обе стороны — реплика без ответа или ответ без реплики.
    try:
        with eng.unit():
            eng.touch_exchange(now)
            reply_id = eng.append_exchange(text, answer, now, arrived_at)
            if inbox_ids:
                claimed = eng.mark_handled(inbox_ids, now, reply_id)
                if len(claimed) != len(inbox_ids):
                    raise _Superseded
    except _Superseded:
        logging.warning(
            "пачку %s забрал другой потребитель — ответ выброшен, T1 откачен",
            list(inbox_ids),
        )
        return Outcome(answer=None, since_search=since_search, superseded=True)

    if announce is not None:
        announce(answer)

    t = time.monotonic()
    turn = eng.snapshot(now)

    new_mood = reflect_mood(turn, text, answer, edges.llm)
    logging.info("reflect_mood: %.1fs", time.monotonic() - t)

    new_assertions = reflect_self(turn, text, answer, edges.llm)
    logging.info("reflect_self: %.1fs", time.monotonic() - t)

    candidates = list(extract_objects(turn, text, answer, edges.llm, findings))
    logging.info("extract_objects: %.1fs", time.monotonic() - t)

    # --- T2: осмысление -------------------------------------------------
    # Настроение, факты о себе и объекты — одна единица: это один вывод из
    # одного обмена, и половина такого вывода хуже, чем его отсутствие.
    # Сеть сюда не заходит.
    with eng.unit():
        if new_mood:
            eng.set_mood(new_mood)
        if new_assertions:
            eng.merge_self_assertions(new_assertions, now)
        for cand in candidates:
            eng.upsert_object(cand, now)

    logging.info("complete_cycle: %.1fs", time.monotonic() - t)
    return Outcome(answer=answer, since_search=since_search)
