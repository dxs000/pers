# Геокодер зовётся один раз за всю жизнь состояния, погода — раз в TTL.
# Ждать минуту, как LLM, тут незачем: не ответили быстро — блок среды
# сегодня беднее.
NET_TIMEOUT = 10.0

# Поиск стоит между репликой человека и ответом — его паузу человек ждёт
# напрямую, поэтому таймаут заметно короче, чем у среды.
SEARCH_TIMEOUT = 8.0

# Сколько ходов после поиска ретривер молчит. Смысл не в экономии вызовов —
# сам проход дёшев и случается всё равно, — а в том, чтобы блок найденного
# не стоял в промпте два хода подряд: иначе персонаж превращается в
# поисковую выдачу с характером. Порог на глаз, правится на живом.
RETRIEVER_COOLDOWN = 3


@dataclass(frozen=True)
class Edges:
    """Края хода: модель, сеть среды, сеть поиска и ключ к ней.

    Всё нечистое, что ходу нужно, приезжает одним объектом и параметром.
    До Шага 27 это были три модульных глобала в `main`, поднимаемые
    лениво; ленивость была нужна ровно затем, чтобы `config._client_kwargs`
    не печатал строку про прокси на каждый запрос. Теперь края поднимаются
    один раз на входе в процесс, и свойство «один клиент на процесс»
    держится устройством, а не памятью о том, зачем тут `global`.

    Ключ поиска лежит здесь, а не читается из `config` по месту, по
    правилу самого `web.search`: «ключ приходит параметром, модуль-край не
    лезет в настройки проекта». Заодно это единственный способ дать сбруе
    детерминированный ход — иначе поиск зависел бы от того, задан ли
    `TAVILY_API_KEY` на конкретной машине.
    """

    llm: Any
    http: Any = None
    search: Any = None
    search_key: str = ""

    def close(self) -> None:
        for client in (self.http, self.search):
            if client is not None:
                client.close()


@dataclass(frozen=True)
class Outcome:
    """Что ход отдаёт наружу. Ни одно поле не про печать.

    `since_search` — значение для СЛЕДУЮЩЕГО хода, а не факт «искали».
    Правило заслонки живёт в одном месте (внутри хода), вызывающий его
    только переносит: считать «0 если искали, иначе +1» у себя значило бы
    завести вторую копию правила, обязанную совпадать с первой.

    `superseded` (Шаг 28) — ход не состоялся, потому что пачку успел забрать
    другой потребитель. Отдельным полем, а не строкой в `error`: ошибки
    показывают человеку («Ошибка запроса: …»), а тут показывать нечего и не
    надо — его слова обработаны, просто не нами. Поле выглядит мёртвым при
    одном демоне и им не является: путь «две копии юнита» стоит в чек-листе
    одноразовых путей (пункт 7), а проверяется он сценарием `inbox`, где обе
    половины гонки разыграны по шагам.
    """

    answer: str | None
    since_search: int
    error: str | None = None
    superseded: bool = False


class _Superseded(Exception):
    """Внутренний сигнал: пачку забрали. Роняет T1, чтобы откатить обмен.

    Исключение, а не проверка после записи, ровно потому, что откатить надо
    ВСЁ: строки `messages` уже вставлены к этому моменту (иначе неоткуда
    взять `reply_id`), и оставить их значило бы получить ответ, которого
    никто не увидит, в середине чужого разговора.
    """


def open_edges() -> Edges:
    """Поднять края процесса. Одна точка на процесс — и у REPL, и у демона.

    Живёт здесь, а не в `main`, ровно затем, зачем `web.build_search_client`
    живёт в `web`: чтобы у `agent.py` (Шаг 29) не появилось второй копии
    сборки, обязанной совпадать с первой. Таких копий проект вычистил уже
    три (формула затухания, досев объекта №0, `sky_snapshot` в сбруе), и
    заводить четвёртую на ровном месте не стоит.

    Ключа модели нет — `config.require_api_key` роняет вызов внятной
    ошибкой, и ловит её тот, у кого есть чем её показать.
    """
    return Edges(
        llm=OpenAI(
            api_key=config.require_api_key(),
            base_url=config.DEEPSEEK_BASE_URL,
            http_client=config.get_sync_client(),
            max_retries=config.MAX_RETRIES,
        ),
        http=config.get_sync_client(timeout=NET_TIMEOUT),
        search=web.build_search_client(SEARCH_TIMEOUT),
        search_key=config.TAVILY_API_KEY,
    )


# --- Среда за окном ---------------------------------------------------------
# `sky_snapshot` отсюда уехал на Шаге 32: расчёт живёт в `sky.local_snapshot`,
# место приезжает параметром. Причина не в красоте, а в том, что фасад —
# дверь писателя, и функция, берущая место через него, была недоступна
# инспектору по устройству. Здесь осталась погода: у неё сеть, а сети у
# инспектора нет и не будет.
def weather_snapshot(place: dict, edges: Edges, now_dt: datetime) -> dict | None:
    """Погода в месте персонажа или `None`. Кэш и режимы отказа — в `outside`.

    Место приходит словарём, а не фасадом, — по той же причине, что у неба,
    и ради того, чтобы `prompt_and_latch` читал его ОДИН раз на ход: две
    половины блока среды обязаны говорить об одном месте.
    """
    pair = sky_mod.coords(place.get("lat"), place.get("lon"))
    if pair is None:
        return None

    try:
        return outside.weather(pair[0], pair[1], now_dt, edges.http)
    except Exception as err:
        logging.warning("weather: слепок не собрался: %s", err)
        return None


def prompt_and_latch(eng, edges: Edges, now_dt: datetime, previous=None,
                     findings: list[dict] | None = None, tz=None) -> str:
    """Системный промпт на момент `now_dt` — и запись латча среды.

    Имя говорит про обе половины, и это правка долга: функция звалась
    `render_system_prompt`, то есть называла себя рендером, а писала в
    хранилище. Пока состояние было словарём, запись выглядела мутацией и
    пряталась; с Шага 23 она стоит внутри `unit()` и прячется хуже, но имя
    по-прежнему врало.

    Единственное место, знающее, из чего собран промпт: память по
    эффективной важности, локальное время, разрыв с прошлой сессией,
    эпизоды, небо и погода за окном, плюс найденное в сети на этом ходу.
    Хранение — UTC, рендер — локальный, конвертация живёт здесь, на краю
    (в `mind` часы не заезжают).

    Пояс приходит параметром, а не берётся из `config` по месту: он —
    настройка ЗАПУСКА, а не свойство хода, и сбруя обязана уметь прибить
    его константой (эталон, зависящий от `.env`, не совпадёт между
    машинами — источник недетерминизма №2 в `golden.py`).

    Запись короткая — один стейтмент, — но единица вокруг неё всё равно
    стоит. Не ради атомарности (её тут нечего защищать), а ради правила
    без исключений: **всякая запись идёт внутри `unit()`**. Правило с
    оговоркой «кроме коротких» не проверяется чтением, а это — да:
    `eng.`-запись вне `with` становится видимой ошибкой.
    """
    tz = tz or config.TZ
    place = eng.place()
    snap = sky_mod.local_snapshot(place.get("lat"), place.get("lon"), now_dt, tz)
    wx = weather_snapshot(place, edges, now_dt)

    prompt = build_system_prompt(
        eng.snapshot(now_dt),
        now_dt.astimezone(tz),
        snap,
        wx,
        previous,
        findings,
    )
    with eng.unit():
        eng.remember_outside(snap, wx, now_dt, weather_family(wx))
    return prompt


def look_outward(user_text: str, objects: list[dict], edges: Edges,
                 since_search: int, now: datetime) -> tuple[list[dict] | None, bool]:
    """Решить, нужен ли веб, и — если заслонка позволяет — сходить.

    Возвращает `(findings, искали_ли)`. `findings is None` значит, что в
    промпте блока не будет вовсе; пустой список — «искали, не нашли», и
    это персонаж вправе произнести.

    **Заслонка отсекает поиск, а не решение.** `decide_query` зовётся в
    любом случае и его вердикт пишется в лог: иначе не узнать, как часто
    ретривер хотел бы стрелять, и `RETRIEVER_COOLDOWN` придётся подгонять
    вслепую. Цена — лишний дешёвый вызов на ходах после поиска.
    """
    query = decide_query(user_text, objects, edges.llm)
    if not query:
        return None, False

    if since_search < RETRIEVER_COOLDOWN:
        logging.info("поиск подавлен заслонкой (%s/%s ходов): «%s»",
                     since_search, RETRIEVER_COOLDOWN, query)
        return None, False

    # Отдельный клиент: прокси проекта поисковые домены не пропускает.
    # `now` — тот же момент, что у всего хода. Кэш поиска обзавёлся сроком
    # (Шаг 25), а часы в этом проекте живут на краю и приходят параметром.
    results = web.search(query, edges.search, edges.search_key, now=now)
    if results is None:
        return None, False

    for item in results:
        logging.info("нашлось: %s | %s", item.get("title"), item.get("url"))
    return results, True


# --- Очередь ----------------------------------------------------------------
@dataclass(frozen=True)
class Batch:
    """Пачка входящих, разрезанная по границе разговора.

    `live` — реплики этого разговора; они склеиваются в одну строку `user`,
    и ответ на них будет один. `stale` — то, что пришло по ту сторону
    разрыва: текст выбрасывается, счёт уходит в `sessions.dropped`.
    """

    live: list[dict]
    stale: list[dict]

    @property
    def text(self) -> str:
        """Склеенные реплики. Перевод строки — самый честный разделитель:
        человек написал их отдельными сообщениями, и в промпте они должны
        выглядеть отдельными строками, а не слипшейся фразой."""
        return "\n".join((r["text"] or "").strip() for r in self.live if r["text"])

    @property
    def arrived_at(self) -> datetime | None:
        """Момент, когда человек ДОГОВОРИЛ, — метка последней склеенной."""
        return self.live[-1]["ts"] if self.live else None

    @property
    def ids(self) -> list[int]:
        return [r["id"] for r in self.live]


def split_batch(rows: list[dict], gap_hours: float = SESSION_GAP_HOURS) -> Batch:
    """Разрезать пачку там, где между репликами прошёл разрыв сессии.

    **Отвечаем только на последнюю — но слышим все.** Решение принято
    роадмапом до кода, и довод в нём не про экономию вызовов: подряд
    ответить на четыре реплики двухчасовой давности — поведение тикет-
    системы, и оно тем хуже, чем внимательнее исполнено. Пропущенные слова
    при этом не теряются, они склеиваются с последней.

    **Но склеивать через разрыв нельзя.** Демон лежал, человек написал в
    10:00, 10:05 и в 13:00. Первые две принадлежат прошлому разговору;
    склей их с третьей — и в одном обмене окажутся реплики с разницей в три
    часа, ровно там, где `session_stale` эти же три часа считает границей.
    Врать в мерке, которой сам меряешь, хуже, чем терять узко и видимо.

    Разрез считается от ПОСЛЕДНЕЙ реплики назад и по первому же разрыву:
    всё, что дальше него, — прошлый разговор целиком. Правило чистое,
    сессии не касается и потому проверяется без базы.
    """
    if not rows:
        return Batch(live=[], stale=[])

    cut = 0
    for i in range(len(rows) - 1, 0, -1):
        span = (rows[i]["ts"] - rows[i - 1]["ts"]).total_seconds() / 3600.0
        if span >= gap_hours:
            cut = i
            break
    return Batch(live=rows[cut:], stale=rows[:cut])


def handle_pending(eng, edges: Edges, now: datetime, *,
                   since_search: int = RETRIEVER_COOLDOWN,
                   announce: Callable[[str], None] | None = None,
                   close_session: Callable[[], object] | None = None,
                   tz=None) -> Outcome | None:
    """Разобрать очередь и сделать ход. Пусто — `None`, и это не ошибка.

    Единственный вход в разговор, и с Шага 28 через него ходит и REPL.
    Своего входа у клиента нет намеренно: заведи его — и `agent.py` принесёт
    вторую копию провода, обязанную совпадать с первой. Таких копий проект
    вычистил четыре, пятую заводить не на чем.

    `close_session` — колбэк того же рода, что `announce`: закрытие сессии
    сетевое (выжимка) и печатающее, а сюда ни сеть ради выжимки, ни печать
    не заходят. Зовётся ПОСЛЕ того, как счёт отброшенного уже прибавлен:
    `close_session` считает длину эпизода как «обмены + dropped», и после
    закрытия прибавлять уже некуда.
    """
    rows = eng.pending()
    if not rows:
        return None

    batch = split_batch(rows)
    if batch.stale:
        logging.info("реплик по ту сторону разрыва: %s — текст выброшен, счёт учтён",
                     len(batch.stale))
        # Одна единица: пометка «прочитано» и счёт «сколько потеряли» — один
        # факт, и половина такого факта хуже, чем его отсутствие. `reply_id`
        # остаётся пустым — это и есть «ответа не будет».
        with eng.unit():
            eng.mark_handled([r["id"] for r in batch.stale], now)
            counted = eng.bump_dropped(len(batch.stale))
        # **Открытой сессии может не быть, и тогда счёту некуда лечь.**
        # Найдено живым прогоном на чистой базе (чек-лист 3c, пункт 7):
        # демон поднялся, разговора в базе нет вовсе, а в очереди лежат
        # реплики по обе стороны разрыва. Обещание «текст выбрасывается,
        # счёт остаётся» тут исполнить нечем — прошлого разговора не
        # существует, и прибавлять не к чему.
        #
        # Это не потеря, и вот почему: строка `inbox` живёт вечно, вместе
        # с текстом и меткой прихода. `dropped` — не единственный след,
        # а удобный: он доезжает до выжимки. Настоящий след — очередь.
        # Молчать об этом всё же нельзя, иначе разойдётся арифметика
        # эпизода, и разойдётся молча.
        if not counted:
            logging.warning(
                "открытой сессии нет — %s отброшенных реплик не попадут в "
                "счёт эпизода; текст остаётся в inbox", len(batch.stale))
        if close_session is not None:
            close_session()

    return handle_turn(
        eng, edges, batch.text, now,
        since_search=since_search, announce=announce, tz=tz,
        arrived_at=batch.arrived_at, inbox_ids=batch.ids,
    )


