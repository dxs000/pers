"""Рукотворный фикстур состояния — эталон вместо выброшенного state.json.

Зачем он есть (ROADMAP, «Чистый старт» и 3a):
  - На переезде state.json выбрасывается, на Linux старт чистый. Пустая база
    ничего не теряет, и проверка «готовый артефакт на живом состоянии» теряет
    эталон. Взамен — этот снимок: полный и НАМЕРЕННЫЙ, а не случайный.
  - Сегодня он нужен для читающей половины 2.5c (Шаг 15): чтобы проверить
    рендер/ранг источника, нужен снимок, где `source` принимает все значения.
  - Дальше живёт как постоянный тестовый ассет: тот же снимок грузится в
    JSON-store и в Postgres-store, оба собирают промпт, промпты диффаются.
    Это единственная проверка, ловящая потерю данных на смене движка.

Почему билдер, а не голый JSON:
  Рендер зависит от `now` (возраст, затухание, отсечка эпизодов, молчание).
  Чтобы проверки были детерминированны, все метки времени отложены от одной
  прикреплённой точки NOW_REF. Билдер держит её константой, которую тестовая
  сбруя импортирует; JSON — его застывший вывод, который грузит `load_state`.

NOW_REF — «сейчас» этого фикстура. Метки заданы как NOW_REF минус столько-то
часов, поэтому под-шаги времени попадают в заранее выбранные корзины
`timeutil.AGE_BUCKETS`, а не в те, что случайно выпадут в день прогона.

Что фикстур намеренно упражняет (по одному читателю на пункт):
  - `source` во всех значениях: user и web на ассершенах объектов, self — на
    self-ассершенах. (`dream` придёт Фазой 7; колонка под него уже названа.)
  - Противоречие бок о бок: у Анны occupation = два разных значения. Механика
    Фазы 2 — разные value при одном key живут рядом, конфликт не резолвится.
  - `low`-ассершены, которые `_TRUSTED_CONF` обязан отсеять (у Анны и в self).
  - Объект с >3 ассершенами (Анна: 5), чтобы `_pick_assertions` резал по
    `_assertion_rank`, а не отдавал всё.
  - Затухание: `кофе` уведён так глубоко по времени, что effective_salience
    падает ниже SALIENCE_FLOOR и объект НЕ рендерится. Остальные выживают.
  - Эпизоды: с выжимкой и без (summary=None — мёртвый груз, пропускается);
    один слишком старый (за EPISODE_MAX_AGE_HOURS — отсекается по возрасту).
  - Буфер ОТКРЫТ (сессия идёт), dropped>0 — «отрезанная голова», которую
    выжимка обязана назвать честно. Сессия не протухла (последний обмен свежий).

Что фикстур сознательно НЕ трогает (названо вслух, чтобы не искать потом):
  - Молчание (`_render_silence`) — свойство render-параметра `last_exchange`,
    который `main` замораживает на старте ПРЕДЫДУЩЕЙ сессией, а не поля
    состояния. В открытой сессии last_exchange_ts свежий → строки молчания нет,
    и это правильно. Чтобы упражнять ветку, тест передаёт `last_exchange`
    отдельным аргументом (например, NOW_REF - 300ч); см. хвост файла.
  - sky/weather — вычисляются на краю (`main`), в состоянии их нет. Латч
    `self["outside"]` лежит для верности (в Postgres это agent.outside_latch),
    но без переданных sky/weather строки «за окном» не будет.
  - Ранг между объектами при обрезке до 7: выживших объектов меньше семи, так
    что `query_object` их все и отдаёт. Ранг ассершенов ВНУТРИ объекта упражнён
    (Анна). Обрезку списка объектов оставляем ненагруженной сознательно.
"""

import json
from datetime import datetime, timedelta, timezone
from pathlib import Path

# «Сейчас» фикстура. Прикреплено намеренно: от него отложены все метки.
NOW_REF = datetime(2026, 1, 15, 9, 0, 0, tzinfo=timezone.utc)

FIXTURE_PATH = Path(__file__).with_name("fixture_state.json")


def load() -> dict:
    """Фикстур с диска. Читатель переехал сюда на Шаге 26.

    Раньше файл читала `store.load_state` — то есть фикстур загружался
    **как состояние работающей программы**, с доливкой умолчаний и
    `ensure_self` поверх. С уходом JSON-движка это перестало иметь
    смысл: фикстур больше не состояние, а **данные для заливки**, и
    читать их должен тот, кто знает их форму, — этот модуль.

    Умолчания не доливаются, и это проверяемо, а не на веру: файл собран
    `build()` со всеми восемью ключами и полным `self`, поэтому все
    `setdefault` прежнего читателя были no-op. Расхождение вылезло бы
    первым же прогоном сбруи — эталоны на Шаге 26 не сдвинулись ни на
    байт, и это и есть доказательство.

    Форму фикстура не трогаем: перевод его в `fixture.sql` — отдельное
    дело со своей ценой (пересборка эталонов), и делать его в шаге про
    удаление движка значило бы смешать два дела в одном.
    """
    return json.loads(FIXTURE_PATH.read_text(encoding="utf-8"))


def _ago(hours: float) -> str:
    """ISO-метка «столько-то часов назад» от NOW_REF."""
    return (NOW_REF - timedelta(hours=hours)).isoformat()


def _assertion(key, value, confidence, hits, hours_ago, source):
    """Ассершен в конечной схеме 2.5c: {key, value, confidence, hits, ts, source}."""
    return {
        "key": key,
        "value": value,
        "confidence": confidence,
        "hits": hits,
        "ts": _ago(hours_ago),
        "source": source,
    }


def build() -> dict:
    """Собрать снимок состояния. Детерминирован при фиксированном NOW_REF."""

    # ---- Объект №0: self ----------------------------------------------------
    # Место разрешено начисто (label == каноническому имени, `asked` не нужен).
    # Поля resolved_at/source/lat/lon в промпт не идут — их читает только
    # `main` для sky/weather; здесь они для верности снимка.
    self = {
        "name": "Костя",
        "traits": ["внимательный", "ироничный", "упрямый"],
        "mood": "сосредоточенное",
        "place": {
            "label": "Тбилиси",
            "lat": 41.6938,
            "lon": 44.8015,
            "source": "geocoder",
            "resolved_at": _ago(720),
        },
        # source="self" на всех — это то, что пишет reflect_self.
        # Пятый (tic) — low, его обязан отсечь _TRUSTED_CONF.
        "assertions": [
            _assertion("name", "Костя", "high", 3, 300, "self"),
            _assertion("occupation", "редактор", "high", 2, 250, "self"),
            _assertion("value", "точность", "med", 1, 120, "self"),
            _assertion("style", "отвечает вопросом на вопрос", "med", 2, 40, "self"),
            _assertion("tic", "переспрашивает даты", "low", 1, 10, "self"),
        ],
        # Латч среды: в Postgres это agent.outside_latch. Без sky/weather на
        # входе рендер его не покажет — лежит для полноты и для теста латча.
        "outside": {
            "ts": _ago(1),
            "light": "day",
            "weather": "clear",
        },
    }

    # ---- Объекты диалога ----------------------------------------------------
    objects = {}

    # obj_1 — Анна: богатый объект. Пять ассершенов (лимит рендера 3 → ранг),
    # противоречие occupation, web-источник у city, low у mood_today.
    objects["obj_1"] = {
        "id": "obj_1",
        "type": "person",
        "label": "Анна",
        "aliases": ["Аня", "Анечка"],
        "assertions": [
            _assertion("occupation", "бэкенд-разработчик", "high", 5, 2, "user"),
            # Противоречие: то же key, другое value — живёт рядом, не резолвится.
            _assertion("occupation", "тимлид", "high", 1, 50, "user"),
            # Источник — сеть: персонаж «сходил и узнал».
            _assertion("city", "Тбилиси", "high", 2, 30, "web"),
            _assertion("hobby", "скалолазание", "med", 1, 100, "user"),
            # low → отсеется _TRUSTED_CONF, в промпт не попадёт.
            _assertion("mood_today", "устала", "low", 1, 2, "user"),
        ],
        "salience": 3.0,
        "last_seen": _ago(2),          # «недавно»
    }

    # obj_2 — Тбилиси: место. Смешанные источники user/web.
    objects["obj_2"] = {
        "id": "obj_2",
        "type": "place",
        "label": "Тбилиси",
        "aliases": ["Тифлис"],
        "assertions": [
            _assertion("country", "Грузия", "high", 3, 30, "user"),
            _assertion("fact", "самый населённый город страны", "med", 1, 30, "web"),
        ],
        "salience": 2.0,
        "last_seen": _ago(30),         # «на днях»
    }

    # obj_3 — Набоков: тема, постарше, но выживает по затуханию.
    objects["obj_3"] = {
        "id": "obj_3",
        "type": "topic",
        "label": "Набоков",
        "aliases": [],
        "assertions": [
            _assertion("work", "Дар", "high", 2, 200, "user"),
        ],
        "salience": 2.0,              # 2.0*0.5^(200/72) ≈ 0.29 ≥ floor
        "last_seen": _ago(200),        # «на прошлой неделе»
    }

    # obj_4 — кофе: намеренно уведён так глубоко, что effective_salience падает
    # ниже SALIENCE_FLOOR и объект НЕ рендерится. Доказывает работу фильтра.
    objects["obj_4"] = {
        "id": "obj_4",
        "type": "thing",
        "label": "кофе",
        "aliases": [],
        "assertions": [
            _assertion("preference", "без сахара", "med", 1, 900, "user"),
        ],
        "salience": 1.0,              # 1.0*0.5^(900/72) ≈ 0.0002 < floor
        "last_seen": _ago(900),
    }

    # ---- Эпизоды ------------------------------------------------------------
    # Порядок записи — по возрастанию ended_at (как копится лента).
    # _pick_episodes идёт с конца, фильтрует, берёт EPISODES_LIMIT=3.
    episodes = [
        # Слишком старый (>1680ч) → отсекается по возрасту, даже с выжимкой.
        {
            "id": "ep_1",
            "started_at": _ago(2010),
            "ended_at": _ago(2000),
            "exchanges": 12,
            "summary": "Первый разговор, ещё присматривались друг к другу.",
        },
        # Выжимка есть, в возрасте → рендерится («пару недель назад»).
        {
            "id": "ep_2",
            "started_at": _ago(305),
            "ended_at": _ago(300),
            "exchanges": 20,
            "summary": "Спорили про Чернышевского, и я горячился — вышло резче, чем хотел.",
        },
        # Выжимка есть → рендерится («на днях»).
        {
            "id": "ep_3",
            "started_at": _ago(63),
            "ended_at": _ago(60),
            "exchanges": 8,
            "summary": "Он принёс кофе, говорили о ерунде, было легко.",
        },
        # summary=None → мёртвый груз, _pick_episodes пропускает.
        {
            "id": "ep_4",
            "started_at": _ago(22),
            "ended_at": _ago(20),
            "exchanges": 5,
            "summary": None,
        },
        # Выжимка есть, свежий → рендерится («недавно»).
        {
            "id": "ep_5",
            "started_at": _ago(6),
            "ended_at": _ago(5),
            "exchanges": 14,
            "summary": "Начали с погоды, а съехали на Набокова, и я увлёкся.",
        },
    ]

    # ---- Буфер: ОТКРЫТАЯ сессия --------------------------------------------
    # dropped=3 — у разговора отрезана голова; выжимка обязана это назвать.
    # Последний обмен 12 минут назад → сессия НЕ протухла (gap 3ч).
    buffer = {
        "started_at": _ago(1.5),
        "dropped": 3,
        "exchanges": [
            {
                "ts": _ago(1.4),
                "user": "Ты дочитал «Дар»?",
                "assistant": "Дочитал. И, кажется, только теперь понял, зачем там вставная биография.",
            },
            {
                "ts": _ago(0.8),
                "user": "А Анна что советовала посмотреть в Тбилиси?",
                "assistant": "Серные бани и подъём к Нарикале — она на этом настаивала.",
            },
            {
                "ts": _ago(0.2),
                "user": "Давай тогда завтра туда и сходим.",
                "assistant": "Договорились. Выйдем пораньше, пока жара не встала.",
            },
        ],
    }

    return {
        "version": 1,
        "self": self,
        "objects": objects,
        "episodes": episodes,
        "buffer": buffer,
        "next_episode_id": 6,          # ep_1..ep_5 заняты
        "last_exchange_ts": _ago(0.2), # совпадает с последним обменом буфера
        "next_id": 5,                  # obj_1..obj_4 заняты
    }


if __name__ == "__main__":
    state = build()
    out = FIXTURE_PATH
    out.write_text(
        json.dumps(state, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )
    print(f"NOW_REF = {NOW_REF.isoformat()}")
    print(f"написан {out} ({out.stat().st_size} байт)")
