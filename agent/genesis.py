"""Тяга рождения: числа, которых никто не выбирал (Шаг 36).

Модуль импортирует из проекта только `timeutil` — тот же лист, что все.
Часов не дёргает, в сеть не ходит, в базу не пишет, модель не зовёт: всё
это приезжает параметрами или случается снаружи.

## Зачем тяга

Спросить у модели «придумай себе дату рождения и место» — значит получить не
выбор персонажа, а моду обучающей выборки: узкую вилку по дате, столицу по
месту и анкетный тон, потому что вопрос задан как анкетный пункт. Хуже того,
запись необратима: плохое рождение не поправить, не снеся биографию.

Отсюда разделение труда. **Число, которое придумала модель, — это число из её
приоров. Число, которое вытянула машина, — число, которого не выбирал никто.**
Модель хороша не в выборе, а в осмыслении: ей отдаётся готовая данность, и
спрашивается не «кто ты», а «что там было». Эта половина — Шаг 36.3b.

## Откуда энтропия

Не из `random()` — из мира. Три вещи, которые к первому ходу уже существуют и
которых никто не подбирал:

    место, где персонаж находится      — единственный факт мира на пустой базе
    момент первого обращения к нему    — реальное время, с сезоном и часом
    первые слова, которые ему сказали  — то, с чем к нему пришли

Один и тот же человек на двух установках не выпадет. На одной и той же —
выпадет тот же самый, и потому тягу проверяет эталон.

## Почему не `random.Random(seed)`

`Random` воспроизводим в пределах версии Python, но `randrange`, `uniform` и
`triangular` переносимыми между версиями не объявлены. Для эталона это значило
бы, что обновление интерпретатора красит сценарий, не изменив ни строки кода.
Числа берутся прямо из байтов sha256 — их форма не изменится никогда.
"""

import hashlib
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from math import asin, atan2, cos, degrees, radians, sin, sqrt

from timeutil import DAYS_IN_YEAR

# =============================================================================
# Рамки мира. НЕ факты жизни
# =============================================================================
# Различение несущее. Факт жизни («родился 3 марта в Гори») принадлежит
# персонажу, и задавать его за него нельзя — тогда биография наша, а не его.
# Рамка («взрослый», «родом откуда-то отсюда») — это то, ВО ЧТО он рождается,
# и её задаёт мир. Человек тоже рождается в ограничения, которых не выбирал;
# `APP_PLACE` в конфиге — ровно такая же рамка, и никого это не смущает.
AGE_BAND = (24, 52)          # полных лет на момент рождения персонажа
BIRTH_RADIUS_KM = 900.0      # предельное удаление места рождения от места жизни
SAME_PLACE_KM = 25.0         # ближе — родился там же, где живёт

# Пола здесь нет: он зашит мужским и живёт там, где читается, — в промптах
# `mind` (36.3b). Тянуть его нельзя, пока служебные промпты проекта написаны
# в мужском роде: вытянутая женщина получила бы черты в чужом роде и
# рассогласование, которое видно только в живой реплике.

EARTH_RADIUS_KM = 6371.0088


# =============================================================================
# Дайджест и вычитывание
# =============================================================================
_DRAW_BYTES = 4
_DRAW_SCALE = float(1 << (8 * _DRAW_BYTES))


def _draw(digest: bytes, index: int) -> float:
    """Число из [0, 1) — очередной кусок дайджеста, прочитанный как целое.

    sha256 даёт 32 байта, то есть восемь таких кусков; сегодня нужны три.
    Индекс явный, а не счётчик состояния: тяга обязана быть чистой функцией,
    и порядок вычитывания должен читаться в коде, а не складываться из
    порядка вызовов.
    """
    start = index * _DRAW_BYTES
    return int.from_bytes(digest[start:start + _DRAW_BYTES], "big") / _DRAW_SCALE


def seed(place_label: str | None, first_text: str | None, now: datetime) -> bytes:
    """Дайджест мира на момент рождения.

    Всё нормализуется, и каждая нормализация закрывает свой способ получить
    разных людей из одного мира: регистр и края — потому что «Тбилиси» и
    « тбилиси » одно место; пробелы внутри реплики — потому что двойной
    пробел не различие; пояс — потому что момент один, как бы он ни записан.

    `timespec="seconds"`: микросекунды сделали бы тягу невоспроизводимой даже
    при одинаковых входах, а секунды уже достаточно, чтобы две установки
    разошлись.
    """
    material = "|".join((
        (place_label or "").strip().lower(),
        " ".join((first_text or "").split()),
        now.astimezone(timezone.utc).isoformat(timespec="seconds"),
    ))
    return hashlib.sha256(material.encode("utf-8")).digest()


def _destination(lat: float, lon: float, bearing_deg: float,
                 distance_km: float) -> tuple[float, float]:
    """Точка на сфере: куда придёшь, пройдя столько-то в такую-то сторону."""
    angular = distance_km / EARTH_RADIUS_KM
    br = radians(bearing_deg)
    p1, l1 = radians(lat), radians(lon)
    p2 = asin(sin(p1) * cos(angular) + cos(p1) * sin(angular) * cos(br))
    l2 = l1 + atan2(sin(br) * sin(angular) * cos(p1),
                    cos(angular) - sin(p1) * sin(p2))
    return degrees(p2), (degrees(l2) + 540.0) % 360.0 - 180.0


# =============================================================================
# Тяга
# =============================================================================
@dataclass(frozen=True)
class Birth:
    """Что вытянулось. Данные, и только: ни рендера, ни решений.

    `age` выводится из `born_at`, но лежит полем — его читает промпт списка
    имён (36.3b), а мода имён когортная: одно место с разницей в двадцать лет
    даёт разные списки. Пересчитывать возраст у каждого читателя значило бы
    завести третью копию `DAYS_IN_YEAR`.
    """

    born_at: datetime
    age: int
    bearing: float          # градусы, 0 — север
    distance_km: float
    lat: float | None       # целевая точка; None, если считать не из чего
    lon: float | None
    same_place: bool        # родился там же, где живёт


def draw(place_label: str | None, place_lat: float | None,
         place_lon: float | None, first_text: str | None,
         now: datetime) -> Birth:
    """Вытянуть рождение. Чистая функция: одни входы — один и тот же человек."""
    digest = seed(place_label, first_text, now)

    # --- когда --------------------------------------------------------------
    low, high = AGE_BAND
    years = low + (high - low) * _draw(digest, 0)
    born = now.astimezone(timezone.utc) - timedelta(days=int(years * DAYS_IN_YEAR))
    # Полночь. Час рождения не читается нигде: `precision` генезисного
    # воспоминания всё равно `era`. В эталоне и в инспекторе он был бы шумом,
    # который выглядит значащим, — а это худший род шума.
    born = born.replace(hour=0, minute=0, second=0, microsecond=0)

    # --- куда ---------------------------------------------------------------
    bearing = round(360.0 * _draw(digest, 1), 1)

    # Треугольное распределение с модой в нуле, взятое обратной функцией:
    # F(x) = 1 - (1 - x/R)², отсюда x = R(1 - sqrt(1 - u)).
    #
    # Мода в нуле — не украшение. Большинство людей рождаются там же, где
    # живут, или неподалёку, и лишь немногие далеко. Равномерное расстояние
    # дало бы обратное: почти все рождались бы у самой границы радиуса,
    # потому что дальнее кольцо шире ближнего.
    distance = round(BIRTH_RADIUS_KM * (1.0 - sqrt(1.0 - _draw(digest, 2))), 1)

    same_place = distance < SAME_PLACE_KM

    # Координат может не быть: место задано именем, а геокодер не помог. Это
    # деградация, а не отказ, — тот же принцип, что у `sky` и `web`. Без точки
    # модель получит только направление и расстояние словами, а проверить её
    # ответ геокодером будет нечем.
    lat = lon = None
    if not same_place and place_lat is not None and place_lon is not None:
        lat, lon = _destination(place_lat, place_lon, bearing, distance)
        # Четыре знака — та же точность, с какой место жизни лежит в базе
        # (`place_lat = 41.6938`). Дальше идут сантиметры, а место рождения
        # это город, а не точка.
        lat, lon = round(lat, 4), round(lon, 4)

    return Birth(born, int(years), bearing, distance, lat, lon, same_place)