"""Снимок хода: то, что `store` собирает, а `mind` читает.

Зачем (ROADMAP, «Новое обстоятельство», п.2):
    Сегодня весь проект возит один словарь `state`. С базой словаря «всего
    состояния» не существует — есть таблицы и запросы, и `mind` обязан
    получать **готовый снимок**, собранный под конкретный ход.

**Модуль не импортирует из проекта ничего** — та же дисциплина, что у
`timeutil` и `sky`. Это не эстетика: снимок — контракт между `store` и
`mind`, и если бы он жил в `store`, то `mind` начал бы зависеть от
хранилища ровно в тот момент, когда его от хранилища отвязывают.

**Здесь нет часов, сети и логики.** Снимок — данные, уже отобранные и уже
нормализованные. Кто их отобрал (JSON-словарь, `SELECT`, тестовый фикстур)
— `mind` не знает и знать не должен.

---

## Три среза объектов, а не один

Это главное, что снимок делает видимым. В JSON-словаре все проходы
итерировались по одному `state["objects"]`, и различие пряталось:

    `objects`  — top-N по `effective_salience`. Память, всплывающая в
                 системном промпте, и метки для ретривера.
    `registry` — ПОЛНЫЙ реестр id/label/aliases. Нужен экстрактору для
                 матчинга: сматчить с забытым объектом нельзя, если его
                 нет в списке, а забытый объект — не удалённый.

В Postgres это два разных запроса (второй — без `ORDER BY` и без
`LIMIT`), и знать об этом надо до `CREATE TABLE`, а не после.

## Ассершены нормализованы, и это несущее решение

`_build_reflector_prompt` кладёт self-ассершены в промпт **дословным
`json.dumps`**. Значит форма хранения протекает в текст: порядок ключей,
формат `ts`, наличие `confirmed`. Из JSON-файла порядок — тот, в котором
писал билдер; из Postgres — тот, в котором вернул `SELECT`, а `ts` вообще
приедет объектом `datetime`, который `json.dumps` не сериализует.

Поэтому ассершен в снимке — не строка таблицы и не запись файла, а
**нормализованная форма с фиксированным порядком полей** (`ASSERTION_FIELDS`).
Нормализует `store`, каждый под свой движок; `mind` получает одинаковое.
Без этого паритет на 3b не сойдётся, и разошёлся бы он в самом неочевидном
месте — внутри JSON-строки внутри промпта.
"""

from dataclasses import dataclass, field
from datetime import timezone


def norm_name(s: str) -> str:
    """Каноничная форма имени/псевдонима для матчинга. ОДНО место на проект.

    Живёт здесь, а не в `store`, по той же причине, что и
    `normalize_assertion`: правило общее для всех движков, и разъехаться
    ему нельзя. Разъехаться оно норовит: SQL-функция `lower()`
    **зависит от локали базы**, и под `C`/`POSIX` не трогает ничего, кроме
    ASCII — `lower('Тифлис')` возвращает `'Тифлис'`. Для проекта, который
    целиком на кириллице, это означало бы, что матчинг по псевдониму молча
    не работает, а расхождение вылезало бы между ноутом и сервером.

    Отсюда решение: **база не складывает регистр вообще.** Нормализованная
    форма считается здесь, на Python, кладётся отдельной колонкой, и
    Postgres сравнивает готовые строки. Тот же приём, что с формулой
    затухания, только строже: там дублирование под присмотром сбруи, здесь
    дублирования нет совсем.
    """
    return (s or "").strip().lower()


def iso(value):
    """`datetime` -> ISO-строка в UTC. Одно место на проект.

    Жила в `store_pg._iso` — там, где её единственный читатель собирал
    снимок, — и это было верно ровно до тех пор, пока читатель был один.
    С Шага 30 их два: снимок отдаёт `ts` промпту рефлектора, инспектор
    отдаёт те же метки наружу. Правило то же, по которому сюда переехали
    `norm_name`, `clip_text` и `SESSION_GAP_HOURS`: форма, которую видит
    читатель, — контракт, а не деталь движка, и разъехаться ему нельзя.

    `astimezone(utc)` не косметика. Один и тот же момент записывается как
    `+00:00` и как `+03:00`, строки получаются разные, а `ts` доезжает до
    промпта рефлектора дословным `json.dumps`. Соединение (`store_pg.connect`
    с `timezone=UTC`) закрывает штатный путь; это — бортик для пути, на
    котором соединение открыл кто-то другой.
    """
    return None if value is None else value.astimezone(timezone.utc).isoformat()


TEXT_LIMIT = 500


def clip_text(text: str, limit: int = TEXT_LIMIT) -> str:
    """Обрезка реплики ДЛЯ ПРОМПТА. Одна на все движки — по той же причине,
    что `norm_name`: обрежь по-разному, и выжимка получит разный текст при
    одинаковом разговоре.

    **Шаг 24: обрезка переехала с записи на чтение.** До него `store` резал
    реплику на входе в хранилище, и обрезанной становилась сама память: после
    рестарта персонаж получал свою же реплику с оборванным хвостом и не имел
    способа узнать, что хвост был. Мотивирована обрезка не хранением — местом
    в промпте выжимки, — и потому живёт там, где промпт собирается.
    """
    text = (text or "").strip()
    # Три точки, а не символ «…»: так писал JSON-движок, а паритет считает
    # байты. Замена на типографское многоточие — отдельное решение, и
    # принимать его надо видя, что оно меняет каждую обрезанную реплику.
    return text if len(text) <= limit else text[:limit].rstrip() + "..."


# Сколько обменов поднимается в рабочую память. СВОЯ константа, а не
# `SUMMARY_EXCHANGES_LIMIT`: там предел про то, сколько разговора влезет в
# промпт выжимки, здесь — про то, сколько его помнит сам персонаж, пока
# говорит. Сегодня оба числа равны сорока, и именно поэтому их нельзя
# сводить в одно: равенство случайно, а место, где оно молча разъедется,
# в проекте уже было (`dropped` в JSON-движке, см. store_pg).
WORKING_MEMORY_EXCHANGES = 40

# Разрыв, после которого разговор считается прошлым. Жил в `store_pg` —
# там, где его читает `session_stale`, — и это было верно ровно до тех пор,
# пока читатель был один. С Шага 28 их два: хранилище спрашивает «протухла
# ли открытая сессия», а `cycle.split_batch` — «принадлежит ли эта реплика
# прошлому разговору». Два ответа на один вопрос обязаны совпадать, и
# держать их совпадение дисциплиной проект уже пробовал трижды (формула
# затухания, досев объекта №0, `sky_snapshot` в сбруе). Константа —
# свойство РАЗГОВОРА, а не таблицы, поэтому переезжает сюда, к остальным
# его меркам, а не дублируется.
SESSION_GAP_HOURS = 3.0


def message(role: str, text: str) -> dict:
    """Реплика -> сообщение для модели. ОДНО место, где живут имена полей.

    Смысл тот же, что у `ASSERTION_FIELDS`: список уезжает в модель как
    есть, поэтому его форма — контракт, а не деталь движка. Собери его
    в `store` и `store_pg` порознь — и разъедется он не диффом снимка, а
    молча, в контексте разговора.
    """
    return {"role": role, "content": text}

# Порядок полей ассершена в промпте. Именно порядок, а не набор: он попадает
# в текст через json.dumps, и его перестановка — изменение промпта.
# `confirmed` в конце и только когда есть: так факт без промоушена выглядит
# в точности как до Шага 15.
ASSERTION_FIELDS = ("key", "value", "confidence", "hits", "ts", "source")

# Черты по умолчанию: то единственное, что есть у персонажа на чистом старте.
# Здесь, а не в движках порознь, — разъехаться им нельзя (см. Шаг 21).
DEFAULT_TRAITS = ("любопытный",)


def normalize_assertion(a) -> dict:
    """Ассершен -> канонная форма для промпта. Порядок полей фиксирован.

    Отсутствующий `source` дефолтится в `user` — то же чтение, что у
    `_assertion_rank` и `_source_mark`. Флаг `confirmed` дописывается
    только истинным: промоушен — событие, а не колонка со значением False.
    """
    out = {}
    for name in ASSERTION_FIELDS:
        value = a.get(name)
        if name == "source" and not value:
            value = "user"
        if value is not None:
            out[name] = value
    if a.get("confirmed"):
        out["confirmed"] = True
    return out


@dataclass(frozen=True)
class Turn:
    """Всё состояние, которое видит `mind` на одном ходу. Больше — ничего.

    `frozen=True` не для красоты: `mind` думает, а не хранит, и попытка
    записать что-то в снимок должна падать сразу, а не тихо потеряться.
    Латч среды пишет `store.remember_outside`, ассершены — `store`, и это
    единственное место, где это записано явно.
    """

    # --- Объект №0 ----------------------------------------------------------
    name: str | None = None
    # ISO-строка, а не `datetime`: снимок отдаёт время читателю в той же
    # форме, что `ts` ассершенов (см. `iso`). Возраст здесь НЕ считается —
    # для этого нужны часы, а часов в этом модуле нет и не будет. Считает
    # `mind`, которому `now` уже приезжает параметром.
    born_at: str | None = None
    birthplace: str | None = None
    traits: tuple[str, ...] = ()
    mood: str = "нейтральное"
    place_label: str | None = None
    self_assertions: list[dict] = field(default_factory=list)
    # Всплывшие воспоминания, УЖЕ отобранные хранилищем. Полного среза,
    # как `registry` у объектов, здесь нет намеренно: реестр объектов нужен
    # экстрактору для матчинга, а сопоставлять воспоминания сегодня некому.
    memories: list[dict] = field(default_factory=list)
    outside_latch: dict | None = None

    # --- Мир ----------------------------------------------------------------
    episodes: list[dict] = field(default_factory=list)
    objects: list[dict] = field(default_factory=list)     # top-N, отобранные
    registry: list[dict] = field(default_factory=list)    # полный, для матчинга

    @property
    def traits_line(self) -> str:
        """Черты одной строкой. Живёт здесь, потому что нужна трём проходам
        одинаково, и три разных `", ".join` — три места, где они разъедутся."""
        return ", ".join(self.traits)
