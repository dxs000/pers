"""Клиент: кладёт реплику в очередь и ждёт ответа (Шаг 29).

Вторая половина расщеплённого `main.py`. Внешне это прежний REPL, внутри —
другое существо: **у него нет фасада хранилища**. `engine` сюда не
импортируется вовсе, и это не экономия импорта, а исполнение принципа
«один писатель памяти». Клиенту доступны ровно три запроса:

    INSERT в `inbox`          — единственное, что он пишет;
    SELECT своей строки       — в каком она состоянии;
    SELECT текста ответа      — что показать человеку.

Их видно глазами, и добавить четвёртый нельзя не заметив. В Фазе 4b на это
место встанет Node с тем же протоколом — он про то, что лежит в базе, а не
про то, кто читает.

## Три терминальных состояния — здесь они и окупаются

Колонки `handled_at` и `reply_id` завелись на Шаге 28 «для клиента», и до
сих пор клиента не было. Теперь есть, и различие работает:

    не помечено                  — персонаж ещё думает, ждём;
    помечено, `reply_id` есть    — ответ вот он; у склеенных реплик он
                                   ОБЩИЙ, и человек увидит один ответ на
                                   две свои строки, что и правда;
    помечено, `reply_id` пуст    — слова прочитаны поздно и ушли в прошлый
                                   разговор; ответа не будет, и сказать об
                                   этом надо, а не ждать молча.

Без третьего состояния клиент висел бы до таймаута на реплике, ответ на
которую не придёт никогда, — и выглядело бы это как зависший демон.

**С Шага 30 само правило живёт не здесь.** Три состояния читает ещё и
инспектор — страницей очереди, — и определение «помечено ли и есть ли
ответ» переехало в `inspector.inbox_state`, к остальным читающим
контрактам. Клиент от этого не потолстел: `engine` сюда по-прежнему не
импортируется, а `inspector` устроен так, что писать им нельзя вовсе.
Проверяется это двумя сценариями сразу: сломай правило — краснеют и
`client`, и `inspector`.
"""

import logging
import sys
import time
from datetime import datetime, timezone

import config
import store_pg
from inspector import ANSWERED, DROPPED, WAITING, inbox_state

# Сколько ждать ответа, прежде чем сказать, что персонаж не отвечает.
#
# Порог щедрый намеренно: на ходу стоит до пяти вызовов модели, и
# нетерпеливое «не отвечает» на медленном канале хуже, чем лишнее ожидание.
# Он же — единственный способ узнать, что демон не запущен: очередь примет
# реплику в любом случае, база про демона ничего не знает.
ANSWER_TIMEOUT = 180.0

# Имена состояний приезжают из `inspector` (Шаг 30). Здесь они стояли
# определением, пока читатель был один; с инспектором их стало два, и
# правило «помечено ли и есть ли ответ» обязано жить в одном месте.
# Разойдись эти два чтения — и человек увидел бы на странице «ответ есть»
# там, где оболочка ждёт до таймаута.
#
# Импорт клиенту ничего не стоит: `inspector` на уровне модуля тянет только
# `store_pg`, который тут и так есть, а `mind` он импортирует лениво.
# Правило «у клиента нет фасада хранилища» не нарушено — `engine` сюда
# по-прежнему не входит, а `inspector` тем и хорош, что писать им нельзя.


def read_state(conn, inbox_id: int) -> tuple[str, str | None]:
    """В каком состоянии моя реплика и что показать.

    Читается СТРОКА, а не уведомление. Уведомление говорит «что-то
    случилось» и теряется вместе с соединением; строка говорит, что именно,
    и переживает всё. Поэтому payload в этом протоколе пуст: два источника
    истины про одно событие — это место, где они разъедутся.
    """
    row = conn.execute(
        "SELECT handled_at, reply_id FROM inbox WHERE id = %s", (inbox_id,)
    ).fetchone()
    state = inbox_state(row)
    if state != ANSWERED:
        return state, None
    answer = conn.execute(
        "SELECT text FROM messages WHERE id = %s", (row["reply_id"],)
    ).fetchone()
    return ANSWERED, (answer or {}).get("text")


def await_reply(conn, inbox_id: int, timeout: float = ANSWER_TIMEOUT):
    """Дождаться терминального состояния своей реплики или сдаться.

    Состояние перепроверяется на каждом пробуждении И один раз до первого
    ожидания. Проверка «до» не для порядка: между `INSERT` и заходом в
    ожидание есть щель, и на быстром ответе демон успевает уложиться в неё
    целиком — тогда уведомление уже прошло, а клиент только собирается
    слушать. Без первой проверки такой разговор висел бы до таймаута,
    причём тем вернее, чем быстрее работает персонаж.
    """
    deadline = time.monotonic() + timeout
    while True:
        state, payload = read_state(conn, inbox_id)
        if state != WAITING:
            return state, payload
        left = deadline - time.monotonic()
        if left <= 0:
            return WAITING, None
        for _ in conn.notifies(timeout=min(left, 5.0), stop_after=1):
            pass


def main() -> int:
    logging.basicConfig(level=logging.WARNING,
                        format="%(levelname)s: %(message)s")
    try:
        conn = store_pg.connect()
    except Exception as err:
        print(err)
        return 1

    # Подписка ДО первой отправки. Наоборот было бы гонкой: ответ на первую
    # реплику мог бы уйти в канал, который ещё никто не слушает.
    store_pg.listen(conn, store_pg.CHANNEL_REPLY)

    print(f"{config.APP_NAME}. Для выхода введите '{config.EXIT_WORD}'")
    print("(отвечает agent.py — если он не запущен, реплики просто лягут в очередь)")

    while True:
        try:
            text = input(f"{config.USER_PROMPT} ")
        except (EOFError, KeyboardInterrupt):
            print()
            break

        if not text.strip():
            continue
        if text.strip().lower() == config.EXIT_WORD:
            break

        # Единственная запись клиента. `NOTIFY` идёт следом, а не тем же
        # стейтментом: под autocommit строка уже видна, и разбудить агента
        # раньше её появления физически нельзя.
        inbox_id = store_pg.push_inbox(conn, text, datetime.now(timezone.utc))
        store_pg.notify(conn, store_pg.CHANNEL_INBOX, str(inbox_id))

        state, answer = await_reply(conn, inbox_id)
        if state == ANSWERED:
            print(f"{config.SYSTEM_PROMPT} {answer}")
        elif state == DROPPED:
            print("(эти слова дошли, но уже к прошлому разговору — "
                  "персонаж их учёл, отвечать не станет)")
        else:
            print(f"(нет ответа за {ANSWER_TIMEOUT:.0f} с — похоже, agent.py "
                  "не запущен; реплика осталась в очереди и дождётся его)")

    conn.close()
    print("Пока !")
    return 0


if __name__ == "__main__":
    sys.exit(main())
